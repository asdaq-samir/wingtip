// Hilt's compiler (2.60.1) reads the Kotlin classes' metadata with the
// kotlin-metadata-jvm it was built with (2.3.21), which refuses Kotlin
// 2.5's ("maximum supported version is 2.4.0", hiltJavaCompileDebug):
// every processor path takes the reader of the Kotlin the app is built
// with, as Dagger's own message says to.
configurations.configureEach {
    resolutionStrategy.eachDependency {
        if (requested.group == "org.jetbrains.kotlin" && requested.name == "kotlin-metadata-jvm") {
            useVersion(libs.versions.kotlin.get())
            because("Hilt's compiler must read Kotlin ${libs.versions.kotlin.get()}'s metadata")
        }
    }
}

