#!/usr/bin/env python3
"""Builds wingtipmaps.app's own site into apps/site/dist: plain HTML and
CSS, the standard library alone, so it needs no npm, no image and no
lockfile, and the same input gives the same bytes on the Mac and in CI.

    python3 apps/site/build.py            write dist/
    python3 apps/site/build.py --out DIR  write somewhere else

What it puts together:
- tokens.css: the colours of design/tokens.json (color.theme light and
  dark, color.brand), the one source the web and the phones take theirs
  from, as CSS custom properties; oklch values written as sRGB hex, which
  every browser reads.
- index.html from src/index.html, in the page layout (src/layout.html).
- privacy/, terms/ and support/ from the web app's own pages
  (apps/web/public/*.html), which the app links to: their body, without
  their own footer, in the site's layout, so the wording has one source.
- assets/: whatever is there (the icon and the screenshot, which
  scripts/build/app-icons.sh and the store framer write), copied as is.
"""

from __future__ import annotations

import argparse
import json
import math
import re
import shutil
from pathlib import Path

SITE = Path(__file__).resolve().parent
REPO = SITE.parent.parent
TOKENS = REPO / "design" / "tokens.json"
WEB_PUBLIC = REPO / "apps" / "web" / "public"

# The web app's legal pages, each one a page of the site at its own path.
LEGAL = {"privacy": "Privacy policy", "terms": "Terms of use", "support": "Support"}


def _lin_to_srgb(c: float) -> float:
    c = max(0.0, min(1.0, c))
    return 12.92 * c if c <= 0.0031308 else 1.055 * c ** (1 / 2.4) - 0.055


def oklch_to_rgb(lightness: float, chroma: float, hue: float) -> tuple[int, int, int]:
    """Björn Ottosson's OKLab to linear sRGB (the CSS Color 4 matrices),
    then the sRGB transfer curve; out-of-gamut channels are clipped."""
    a = chroma * math.cos(math.radians(hue))
    b = chroma * math.sin(math.radians(hue))
    l_ = (lightness + 0.3963377774 * a + 0.2158037573 * b) ** 3
    m_ = (lightness - 0.1055613458 * a - 0.0638541728 * b) ** 3
    s_ = (lightness - 0.0894841775 * a - 1.2914855480 * b) ** 3
    r = 4.0767416621 * l_ - 3.3077115913 * m_ + 0.2309699292 * s_
    g = -1.2684380046 * l_ + 2.6097574011 * m_ - 0.3413193965 * s_
    bl = -0.0041960863 * l_ - 0.7034186147 * m_ + 1.7076147010 * s_
    return tuple(round(_lin_to_srgb(v) * 255) for v in (r, g, bl))  # type: ignore[return-value]


OKLCH = re.compile(r"oklch\(\s*([\d.]+)\s+([\d.]+)\s+([\d.]+)\s*(?:/\s*([\d.]+)%)?\s*\)")


def css_colour(value: str) -> str:
    """A token's colour as CSS every browser reads: hex, or rgb() with
    its alpha where the token has one."""
    m = OKLCH.fullmatch(value.strip())
    if not m:
        return value
    r, g, b = oklch_to_rgb(float(m[1]), float(m[2]), float(m[3]))
    if m[4] is not None:
        return f"rgb({r} {g} {b} / {m[4]}%)"
    return f"#{r:02x}{g:02x}{b:02x}"


def resolve(tokens: dict, value: str) -> str:
    """Follows a "{color.theme.light.x}" reference to its value."""
    while isinstance(value, str) and value.startswith("{"):
        node = tokens
        for part in value.strip("{}").split("."):
            node = node[part]
        value = node["$value"]
    return value


def tokens_css(tokens: dict) -> str:
    theme = tokens["color"]["theme"]
    brand = tokens["color"]["brand"]

    def block(group: dict, prefix: str = "") -> list[str]:
        return [
            f"  --{prefix}{name}: {css_colour(resolve(tokens, spec['$value']))};"
            for name, spec in group.items()
            if not name.startswith("$")
        ]

    lines = [
        "/* Generated by apps/site/build.py from design/tokens.json: edit that file. */",
        ":root {",
        "  color-scheme: light dark;",
        *block(theme["light"]),
        *block(brand, "brand-"),
        "}",
        "@media (prefers-color-scheme: dark) {",
        "  :root {",
        *("  " + line for line in block(theme["dark"])),
        "  }",
        "}",
        "",
    ]
    return "\n".join(lines)


BODY = re.compile(r"<body[^>]*>(.*?)</body>", re.S)
OWN_NAV = re.compile(r"<nav>.*?</nav>", re.S)


def legal_body(name: str) -> str:
    """The web page's words for the site: its body without its own footer
    (the site's layout has one), its links to /app/<page>.html pointed at
    the site's own /<page>/."""
    html = (WEB_PUBLIC / f"{name}.html").read_text(encoding="utf-8")
    m = BODY.search(html)
    if not m:
        raise SystemExit(f"build.py: no <body> in apps/web/public/{name}.html")
    body = OWN_NAV.sub("", m[1]).strip()
    for page in LEGAL:
        body = body.replace(f'href="/app/{page}.html"', f'href="/{page}/"')
    return f'<article class="prose">\n{body}\n</article>'


def page(layout: str, title: str, description: str, main: str) -> str:
    return layout.replace("{{title}}", title).replace("{{description}}", description).replace("{{main}}", main)


def build(out: Path) -> list[Path]:
    tokens = json.loads(TOKENS.read_text(encoding="utf-8"))
    layout = (SITE / "src" / "layout.html").read_text(encoding="utf-8")
    if out.exists():
        shutil.rmtree(out)
    out.mkdir(parents=True)
    written: list[Path] = []

    def write(rel: str, text: str) -> None:
        path = out / rel
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(text, encoding="utf-8")
        written.append(path)

    write("tokens.css", tokens_css(tokens))
    write("site.css", (SITE / "src" / "site.css").read_text(encoding="utf-8"))
    index = (SITE / "src" / "index.html").read_text(encoding="utf-8")
    write(
        "index.html",
        page(
            layout,
            "Wingtip Maps",
            "The FAA chart on a map that works like Maps, and the route, Brief and nav log for a VFR or IFR flight.",
            index,
        ),
    )
    for name, title in LEGAL.items():
        write(f"{name}/index.html", page(layout, f"{title} · Wingtip Maps", title, legal_body(name)))
    write(
        "404.html",
        page(
            layout,
            "Not found · Wingtip Maps",
            "Not found",
            '<article class="prose"><h1>Not found</h1><p><a href="/">Wingtip Maps</a></p></article>',
        ),
    )
    assets = SITE / "assets"
    if assets.is_dir():
        for src in sorted(assets.iterdir()):
            if src.is_file() and not src.name.startswith("."):
                (out / "assets").mkdir(exist_ok=True)
                shutil.copy2(src, out / "assets" / src.name)
                written.append(out / "assets" / src.name)
    return written


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    parser.add_argument("--out", type=Path, default=SITE / "dist")
    args = parser.parse_args()
    written = build(args.out)
    print(f"build.py: {len(written)} files in {args.out}")


if __name__ == "__main__":
    main()
