//! The engine's contract, assembled. Each rule states its input, its
//! answer, its description (with the CFR, AIM or handbook source of its
//! figures) and its flags in a file of its own beside its code:
//! `engine/crates/<crate>/contract/<name>.json`, the file's name the
//! rule's; the facade answers none itself. The same file says which Rust
//! function answers it (`"x-call"`, and `"x-feature"` where a cargo feature
//! gates it), which the facade's build script reads to build the
//! dispatcher (engine/facade/build.rs), so the dispatcher and the contract
//! come from one list and cannot disagree. A type more than one rule uses
//! is a file in a `contract/definitions/` folder: the crate's own where
//! only its rules use it, `engine/contract/definitions/` where several
//! crates' do.
//!
//! This writes them into the one `engine/contract/engine.schema.json` the
//! apps' types, the assistant's tools and the contract tests read, with
//! the rules and definitions in order of name, so two branches that each
//! add a rule add two files and never touch the same line.

// A tool on the host, not in the WebAssembly, so the slices' own sorts
// are fine here (engine/clippy.toml).
#![allow(clippy::disallowed_methods)]

use serde_json::{Map, Value};
use std::collections::BTreeMap;
use std::fs;
use std::io::Write;
use std::path::{Path, PathBuf};

/// The members a rule's file has for the engine's build only, left out of
/// the contract.
pub const BUILD_ONLY: [&str; 2] = ["x-call", "x-feature"];

const DESCRIPTION: &str = "The engine's calls (engine/facade/src/call.rs): for each name, the JSON input it takes and the JSON answer it gives. Generated by wingtip-contract-gen (engine/contract/gen) from each rule's own file beside its code (engine/crates/<crate>/contract/<name>.json) and the types they share (contract/definitions/): change those, not this file. apps/web/src/lib/engine/contract.ts is generated from it (npm run types), and engine/facade/tests/contract.rs holds the engine's answers to it. A member left out of `required` may be missing; a type with null may be null.";

/// The folders that hold rules: each crate's, in order.
pub fn rule_dirs(engine: &Path) -> Result<Vec<PathBuf>, String> {
    let crates = engine.join("crates");
    let mut each: Vec<PathBuf> = fs::read_dir(&crates)
        .map_err(|e| format!("{}: {e}", crates.display()))?
        .filter_map(|d| d.ok().map(|d| d.path().join("contract")))
        .filter(|d| d.is_dir())
        .collect();
    each.sort();
    Ok(each)
}

/// The `.json` files directly in `dir`, by name; none where it is missing.
fn json_files(dir: &Path) -> Result<Vec<PathBuf>, String> {
    if !dir.is_dir() {
        return Ok(Vec::new());
    }
    let mut files: Vec<PathBuf> = fs::read_dir(dir)
        .map_err(|e| format!("{}: {e}", dir.display()))?
        .filter_map(|d| d.ok().map(|d| d.path()))
        .filter(|p| p.is_file() && p.extension().is_some_and(|x| x == "json"))
        .collect();
    files.sort();
    Ok(files)
}

fn read(path: &Path) -> Result<(String, Map<String, Value>), String> {
    let name = path.file_stem().and_then(|s| s.to_str()).ok_or_else(|| format!("{}: no name", path.display()))?.to_owned();
    let text = fs::read_to_string(path).map_err(|e| format!("{}: {e}", path.display()))?;
    match serde_json::from_str(&text).map_err(|e| format!("{}: {e}", path.display()))? {
        Value::Object(members) => Ok((name, members)),
        _ => Err(format!("{}: not a JSON object", path.display())),
    }
}

/// Every `#/definitions/` name `v` refers to.
fn refs(v: &Value, out: &mut Vec<String>) {
    match v {
        Value::Object(m) => {
            for (k, x) in m {
                match (k.as_str(), x) {
                    ("$ref", Value::String(r)) => {
                        if let Some(name) = r.strip_prefix("#/definitions/") {
                            out.push(name.to_owned());
                        }
                    }
                    _ => refs(x, out),
                }
            }
        }
        Value::Array(a) => a.iter().for_each(|x| refs(x, out)),
        _ => {}
    }
}

/// The contract, from the rules' and definitions' files under `engine`.
pub fn assemble(engine: &Path) -> Result<Value, String> {
    let mut rules: BTreeMap<String, (PathBuf, Map<String, Value>)> = BTreeMap::new();
    let mut defs: BTreeMap<String, (PathBuf, Value)> = BTreeMap::new();
    let mut def_dirs = vec![engine.join("contract/definitions")];
    for dir in rule_dirs(engine)? {
        def_dirs.push(dir.join("definitions"));
        for path in json_files(&dir)? {
            let (name, mut rule) = read(&path)?;
            if name.is_empty() || !name.chars().all(|c| c.is_ascii_lowercase() || c.is_ascii_digit() || c == '_') {
                return Err(format!("{}: a rule's name is snake_case", path.display()));
            }
            match rule.get("x-call") {
                Some(Value::String(_)) => {}
                _ => return Err(format!("{}: no \"x-call\", the Rust function that answers it", path.display())),
            }
            for key in BUILD_ONLY {
                rule.shift_remove(key);
            }
            if let Some((first, _)) = rules.get(&name) {
                return Err(format!("{name}: in both {} and {}", first.display(), path.display()));
            }
            rules.insert(name, (path, rule));
        }
    }
    for dir in def_dirs {
        for path in json_files(&dir)? {
            let (name, def) = read(&path)?;
            if let Some((first, _)) = defs.get(&name) {
                return Err(format!("the type {name}: in both {} and {}", first.display(), path.display()));
            }
            defs.insert(name, (path, Value::Object(def)));
        }
    }
    for (path, v) in rules.values().map(|(p, r)| (p, Value::Object(r.clone()))).chain(defs.values().map(|(p, d)| (p, d.clone()))) {
        let mut found = Vec::new();
        refs(&v, &mut found);
        if let Some(missing) = found.iter().find(|r| !defs.contains_key(*r)) {
            return Err(format!("{}: refers to the type {missing}, which no contract/definitions folder has", path.display()));
        }
    }

    let mut top = Map::new();
    top.insert("$schema".into(), "http://json-schema.org/draft-07/schema#".into());
    top.insert("title".into(), "EngineContract".into());
    top.insert("description".into(), DESCRIPTION.into());
    top.insert("type".into(), "object".into());
    let names: Vec<Value> = rules.keys().map(|n| Value::String(n.clone())).collect();
    let properties: Map<String, Value> = rules.into_iter().map(|(n, (_, r))| (n, Value::Object(r))).collect();
    top.insert("properties".into(), Value::Object(properties));
    top.insert("required".into(), Value::Array(names));
    top.insert("additionalProperties".into(), Value::Bool(false));
    top.insert("definitions".into(), Value::Object(defs.into_iter().map(|(n, (_, d))| (n, d)).collect()));
    Ok(Value::Object(top))
}

/// `v` as the committed file is written: two-space indents and every
/// character past ASCII escaped (as Python's json.dump writes it, which
/// wrote the contract before it was generated), with a newline at the end.
pub fn text(v: &Value) -> String {
    let mut out = Vec::new();
    let mut ser = serde_json::Serializer::with_formatter(&mut out, Ascii(serde_json::ser::PrettyFormatter::with_indent(b"  ")));
    serde::Serialize::serialize(v, &mut ser).expect("a JSON value serializes");
    let mut s = String::from_utf8(out).expect("ASCII");
    s.push('\n');
    s
}

/// The engine's folder, from this crate's.
pub fn engine_dir() -> PathBuf {
    let dir = PathBuf::from(env!("CARGO_MANIFEST_DIR")).join("../..");
    dir.canonicalize().unwrap_or(dir)
}

pub fn schema_path(engine: &Path) -> PathBuf {
    engine.join("contract/engine.schema.json")
}

/// The pretty formatter, with a string's characters past ASCII written as
/// `\uXXXX` (two, a surrogate pair, past the Basic Multilingual Plane).
struct Ascii<'a>(serde_json::ser::PrettyFormatter<'a>);

impl serde_json::ser::Formatter for Ascii<'_> {
    fn write_string_fragment<W: ?Sized + Write>(&mut self, w: &mut W, fragment: &str) -> std::io::Result<()> {
        for c in fragment.chars() {
            if c.is_ascii() {
                w.write_all(&[c as u8])?;
            } else {
                let mut units = [0u16; 2];
                for u in c.encode_utf16(&mut units) {
                    write!(w, "\\u{:04x}", u)?;
                }
            }
        }
        Ok(())
    }
    fn begin_array<W: ?Sized + Write>(&mut self, w: &mut W) -> std::io::Result<()> {
        self.0.begin_array(w)
    }
    fn end_array<W: ?Sized + Write>(&mut self, w: &mut W) -> std::io::Result<()> {
        self.0.end_array(w)
    }
    fn begin_array_value<W: ?Sized + Write>(&mut self, w: &mut W, first: bool) -> std::io::Result<()> {
        self.0.begin_array_value(w, first)
    }
    fn end_array_value<W: ?Sized + Write>(&mut self, w: &mut W) -> std::io::Result<()> {
        self.0.end_array_value(w)
    }
    fn begin_object<W: ?Sized + Write>(&mut self, w: &mut W) -> std::io::Result<()> {
        self.0.begin_object(w)
    }
    fn end_object<W: ?Sized + Write>(&mut self, w: &mut W) -> std::io::Result<()> {
        self.0.end_object(w)
    }
    fn begin_object_key<W: ?Sized + Write>(&mut self, w: &mut W, first: bool) -> std::io::Result<()> {
        self.0.begin_object_key(w, first)
    }
    fn begin_object_value<W: ?Sized + Write>(&mut self, w: &mut W) -> std::io::Result<()> {
        self.0.begin_object_value(w)
    }
    fn end_object_value<W: ?Sized + Write>(&mut self, w: &mut W) -> std::io::Result<()> {
        self.0.end_object_value(w)
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    /// The committed contract is the one the rules' files give: a rule's
    /// file changed and the contract not written again fails here (and in
    /// CI, which runs this).
    #[test]
    fn the_committed_contract_is_the_generated_one() {
        let engine = engine_dir();
        let want = text(&assemble(&engine).unwrap_or_else(|e| panic!("{e}")));
        let have = fs::read_to_string(schema_path(&engine)).unwrap();
        assert!(have == want, "engine/contract/engine.schema.json is not what the rules' contract files give: run `cargo run -p wingtip-contract-gen` in engine/ and commit it");
    }

    #[test]
    fn a_character_past_ascii_is_escaped_as_python_wrote_it() {
        assert_eq!(text(&Value::String("90° ✈ 𝄞".into())), "\"90\\u00b0 \\u2708 \\ud834\\udd1e\"\n");
    }
}
