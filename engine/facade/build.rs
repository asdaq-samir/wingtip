//! The dispatcher's table (src/call.rs), written from the rules' own
//! contract files: each `contract/<name>.json` in each crate names its
//! rule (the file's name) and the function that answers it (`"x-call"`,
//! `fn(&str, &Value) -> Result<String, String>`), and `"x-feature"` where a cargo feature of this crate gates it. The same
//! files are the contract (engine/contract/gen), so a name is answered
//! exactly when the contract has it, and adding a rule adds a file rather
//! than a line to a shared list.
//!
//! The files are read with serde_json, a build-dependency only: it runs
//! on the host and is in none of the engine's builds (README.md), where
//! a search of the text for a member would take one in a description or
//! a nested schema for it.

// The build script runs on the host and is not in the WebAssembly, so the
// slices' own sorts are fine here (engine/clippy.toml).
#![allow(clippy::disallowed_methods)]

use std::fs;
use std::path::{Path, PathBuf};

/// The top-level string member `key` of a contract file, or None.
fn member(file: &serde_json::Value, key: &str) -> Option<String> {
    file.get(key)?.as_str().map(str::to_owned)
}

fn json_files(dir: &Path) -> Vec<PathBuf> {
    println!("cargo:rerun-if-changed={}", dir.display());
    let Ok(read) = fs::read_dir(dir) else { return Vec::new() };
    let mut files: Vec<PathBuf> =
        read.filter_map(|d| d.ok().map(|d| d.path())).filter(|p| p.is_file() && p.extension().is_some_and(|x| x == "json")).collect();
    files.sort();
    files
}

fn main() {
    let here = PathBuf::from(std::env::var("CARGO_MANIFEST_DIR").unwrap());
    let crates = here.join("../crates");
    println!("cargo:rerun-if-changed={}", crates.display());
    let mut dirs: Vec<PathBuf> =
        fs::read_dir(&crates).unwrap().filter_map(|d| d.ok().map(|d| d.path().join("contract"))).filter(|d| d.is_dir()).collect();
    dirs.sort();

    // The web's WebAssembly, the one build for wasm32 (bindings/wasm): only
    // the rules the web asks, as scripts/build/web_rules.py lists them from
    // its code. By the target, not a cargo feature: a feature would be
    // unified into every build of the workspace that has bindings/wasm in
    // it (`cargo test --workspace`), and the planner's wheel and the phones
    // build every rule.
    let wasm = std::env::var("CARGO_CFG_TARGET_ARCH").is_ok_and(|a| a == "wasm32");
    let web: Option<Vec<String>> = wasm.then(|| {
        let list = here.join("web-rules.txt");
        println!("cargo:rerun-if-changed={}", list.display());
        let text = fs::read_to_string(&list).unwrap_or_else(|e| panic!("{}: {e}", list.display()));
        text.lines().map(str::trim).filter(|l| !l.is_empty() && !l.starts_with('#')).map(str::to_owned).collect()
    });

    let mut rules: Vec<(String, String)> = Vec::new();
    for dir in dirs {
        for path in json_files(&dir) {
            println!("cargo:rerun-if-changed={}", path.display());
            let name = path.file_stem().unwrap().to_str().unwrap().to_owned();
            let file: serde_json::Value =
                serde_json::from_str(&fs::read_to_string(&path).unwrap()).unwrap_or_else(|e| panic!("{}: not JSON: {e}", path.display()));
            let call = member(&file, "x-call").unwrap_or_else(|| panic!("{}: no \"x-call\"", path.display()));
            assert!(
                call.chars().all(|c| c.is_ascii_alphanumeric() || c == '_' || c == ':'),
                "{}: \"x-call\" is not a Rust path",
                path.display()
            );
            if let Some(feature) = member(&file, "x-feature") {
                let var = format!("CARGO_FEATURE_{}", feature.to_uppercase().replace('-', "_"));
                if std::env::var_os(var).is_none() {
                    continue;
                }
            }
            assert!(!rules.iter().any(|(n, _)| *n == name), "{name}: two contract files");
            rules.push((name, call));
        }
    }
    if let Some(web) = &web {
        for name in web {
            assert!(rules.iter().any(|(n, _)| n == name), "web-rules.txt: the web asks {name}, which this build has not");
        }
        rules.retain(|(n, _)| web.contains(n));
    }
    rules.sort();

    let mut out =
        String::from("// Generated by build.rs from the rules' contract files.\npub(crate) static RULES: &[(&str, Handler)] = &[\n");
    for (name, call) in &rules {
        out.push_str(&format!("    ({name:?}, {call}),\n"));
    }
    out.push_str("];\n");
    let path = PathBuf::from(std::env::var("OUT_DIR").unwrap()).join("rules.rs");
    fs::write(path, out).unwrap();
}
