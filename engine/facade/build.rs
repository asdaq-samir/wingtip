//! The dispatcher's table (src/call.rs), written from the rules' own
//! contract files: each `contract/<name>.json` in the facade and in each
//! crate names its rule (the file's name) and the function that answers it
//! (`"x-call"`, `fn(&str, &Value) -> Result<String, String>`), and
//! `"x-feature"` where a cargo feature of this crate gates it. The same
//! files are the contract (engine/contract/gen), so a name is answered
//! exactly when the contract has it, and adding a rule adds a file rather
//! than a line to a shared list.
//!
//! No JSON reader: the engine builds with nothing from outside the
//! workspace (README.md), and the two members it reads are plain strings
//! written by the contract's own tooling.

use std::fs;
use std::path::{Path, PathBuf};

/// The string member `key` of a contract file's text, or None.
fn member(text: &str, key: &str) -> Option<String> {
    let at = text.find(&format!("\"{key}\""))?;
    let rest = &text[at + key.len() + 2..];
    let rest = rest.trim_start().strip_prefix(':')?.trim_start().strip_prefix('"')?;
    Some(rest[..rest.find('"')?].to_owned())
}

fn json_files(dir: &Path) -> Vec<PathBuf> {
    println!("cargo:rerun-if-changed={}", dir.display());
    let Ok(read) = fs::read_dir(dir) else { return Vec::new() };
    let mut files: Vec<PathBuf> = read.filter_map(|d| d.ok().map(|d| d.path())).filter(|p| p.is_file() && p.extension().is_some_and(|x| x == "json")).collect();
    files.sort();
    files
}

fn main() {
    let here = PathBuf::from(std::env::var("CARGO_MANIFEST_DIR").unwrap());
    let crates = here.join("../crates");
    println!("cargo:rerun-if-changed={}", crates.display());
    let mut dirs = vec![here.join("contract")];
    let mut each: Vec<PathBuf> = fs::read_dir(&crates).unwrap().filter_map(|d| d.ok().map(|d| d.path().join("contract"))).filter(|d| d.is_dir()).collect();
    each.sort();
    dirs.extend(each);

    let mut rules: Vec<(String, String)> = Vec::new();
    for dir in dirs {
        for path in json_files(&dir) {
            println!("cargo:rerun-if-changed={}", path.display());
            let name = path.file_stem().unwrap().to_str().unwrap().to_owned();
            let text = fs::read_to_string(&path).unwrap();
            let call = member(&text, "x-call").unwrap_or_else(|| panic!("{}: no \"x-call\"", path.display()));
            assert!(call.chars().all(|c| c.is_ascii_alphanumeric() || c == '_' || c == ':'), "{}: \"x-call\" is not a Rust path", path.display());
            if let Some(feature) = member(&text, "x-feature") {
                let var = format!("CARGO_FEATURE_{}", feature.to_uppercase().replace('-', "_"));
                if std::env::var_os(var).is_none() {
                    continue;
                }
            }
            assert!(!rules.iter().any(|(n, _)| *n == name), "{name}: two contract files");
            rules.push((name, call));
        }
    }
    rules.sort();

    let mut out = String::from("// Generated by build.rs from the rules' contract files.\npub(crate) static RULES: &[(&str, Handler)] = &[\n");
    for (name, call) in &rules {
        out.push_str(&format!("    ({name:?}, {call}),\n"));
    }
    out.push_str("];\n");
    let path = PathBuf::from(std::env::var("OUT_DIR").unwrap()).join("rules.rs");
    fs::write(path, out).unwrap();
}
