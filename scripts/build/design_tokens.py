def swift_colour(c):
    r, g, b, a = c
    if a >= 1:
        return "rgb(0x%02X%02X%02X)" % (r, g, b)
    return "rgb(0x%02X%02X%02X, %s)" % (r, g, b, ("%.3f" % a).rstrip("0").rstrip("."))


