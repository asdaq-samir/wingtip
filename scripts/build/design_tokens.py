WEIGHTS = {400: "regular", 500: "medium", 600: "semibold", 700: "bold"}

# The size each iOS text style has at the default (Large) text size: a role
# whose own size is its style's takes the style; one that is not is scaled
# with it (UIFontMetrics), so both follow Dynamic Type.
# fmt: off
IOS_DEFAULT_SIZE = {"title": 28, "title2": 22, "title3": 20, "headline": 17, "body": 17,
                    "subheadline": 15, "footnote": 13, "caption": 12, "caption2": 11}
# fmt: on


def gen_swift(tree, sch):
    names = all_names(sch)
    L = ["// %s" % BANNER, "", "import SwiftUI", "import UIKit", ""]
    L += [
        "/// A colour from its 0xRRGGBB and an alpha.",
        "private func rgb(_ hex: UInt32, _ alpha: CGFloat = 1) -> UIColor {",
        "    UIColor(red: CGFloat((hex >> 16) & 0xFF) / 255, green: CGFloat((hex >> 8) & 0xFF) / 255,",
        "            blue: CGFloat(hex & 0xFF) / 255, alpha: alpha)",
        "}",
        "",
    ]
    L += ["/// Wingtip's colours: the chart's, the flight categories', the mark's, the badges'.", "enum WingtipColor {"]
    for group in SHARED:
        L.append("    enum %s {" % group.capitalize())
        for k, t in tokens(lookup(tree, "color." + group)).items():
            if "$description" in t:
                L.append("        /// %s" % t["$description"])
            L.append("        static let %s = %s" % (camel(k), swift_colour(rgba(css_value(tree, t["$value"])))))
        L.append("    }")
    L += ["}", ""]
    L.append("/// One scheme's surfaces, words and states, as the web's cascade resolves them (color.theme, color.look).")
    L.append("struct WingtipPalette: Sendable {")
    for n in names:
        L.append("    let %s: UIColor" % camel(n))
    L.append("")
    for s, cols in sch.items():
        L.append("    static let %s = WingtipPalette(" % s)
        fallback = sch["dark" if "Dark" in s or s == "dark" else "light"]
        args = []
        for n in names:
            c = cols.get(n) or fallback.get(n) or (0, 0, 0, 0.0)
            args.append("        %s: %s" % (camel(n), swift_colour(c)))
        L.append(",\n".join(args))
        L.append("    )")
    L.append("}")
    L.append("")
    L.append("/// The text roles, each a Dynamic Type style (or a size scaled with one), so")
    L.append("/// every one grows with the pilot's text size.")
    L.append("enum WingtipType {")
    for k, r in tokens(tree["type"]).items():
        v, ext = r["$value"], r.get("$extensions", {}).get(EXT, {})
        style = ext.get("ios")
        if not style or "fontSize" not in v:
            continue
        w = WEIGHTS[v.get("fontWeight", 400)]
        if "$description" in r:
            L.append("    /// %s" % r["$description"])
        if IOS_DEFAULT_SIZE[style] == v["fontSize"]:
            expr = "Font.system(%s, weight: .%s)" % (IOS_STYLES[style], w)
            decl = "static let"
        else:
            scaled = "Font(UIFontMetrics(forTextStyle: %s).scaledFont(for: UIFont.systemFont(ofSize: %g, weight: .%s)))"
            expr, decl = scaled % (UIKIT_STYLES[style], v["fontSize"], w), "static var"
        if v.get("tabular"):
            expr += ".monospacedDigit()"
        L.append(
            "    %s %s: Font %s %s" % (decl, camel(k), "{" if decl == "static var" else "=", expr + (" }" if decl == "static var" else ""))
        )
        if decl == "static var":  # its size too, for a view's @ScaledMetric: SwiftUI never redraws a scaled UIFont by itself
            L.append("    /// %s's size at the default text size, for @ScaledMetric(relativeTo: %s)." % (camel(k), IOS_STYLES[style]))
            L.append("    static let %sSize: CGFloat = %g" % (camel(k), v["fontSize"]))
        if "letterSpacing" in v:
            L.append("    /// %s's letter spacing in points (%gem)." % (camel(k), v["letterSpacing"]))
            L.append("    static let %sTracking: CGFloat = %g" % (camel(k), round(v["letterSpacing"] * v["fontSize"], 2)))
    L.append("}")
    L.append("")
    for enum, group, unit in (("WingtipSpace", "space", "CGFloat"), ("WingtipRadius", "radius", "CGFloat")):
        L.append("enum %s {" % enum)
        for k, t in tokens(tree[group]).items():
            L.append("    static let %s: %s = %g" % (camel(k), unit, t["$value"]))
        L.append("}")
        L.append("")
    L.append("/// Motion: durations in seconds, curves as cubic-bezier points.")
    L.append("enum WingtipMotion {")
    for k, t in tokens(tree["motion"]).items():
        v = t["$value"]
        if isinstance(v, list):
            L.append(
                "    static let %s = Animation.timingCurve(%s, duration: %g)"
                % (camel(k), ", ".join("%g" % x for x in v), tree["motion"]["sheet"]["$value"])
            )
        else:
            L.append("    static let %s: TimeInterval = %g" % (camel(k), v))
    L.append("}")
    L.append("")
    L += haptic.swift(tokens(tree["haptic"]), camel) + [flow.swift(tree), ""]
    L.append("enum WingtipSize {")
    for k, t in tokens(tree["size"]).items():
        L.append("    static let %s: CGFloat = %g" % (camel(k), t["$value"]))
    mat = tokens(tree["material"])
    L.append("    static let glassBlur: CGFloat = %g" % mat["glass-blur"]["$value"])
    L.append("}")
    return "\n".join(L) + "\n"


# ---------------------------------------------------------------- Android


def kt_colour(c):
    if isinstance(c, system.SystemRef):
        return "Color.Unspecified"
    r, g, b, a = c
    return "Color(0x%02X%02X%02X%02X)" % (round(a * 255), r, g, b)


def gen_kotlin(tree, sch):
    names = all_names(sch)
    L = [
        "// %s" % BANNER,
        "",
        "package app.wingtipmaps.android.design.generated",
        "",
        *haptic.KOTLIN_IMPORTS,
        "import androidx.compose.animation.core.CubicBezierEasing",
        "import androidx.compose.material3.ColorScheme",
        "import androidx.compose.material3.Typography",
        "import androidx.compose.runtime.Immutable",
        "import androidx.compose.ui.graphics.Color",
        "import androidx.compose.ui.text.TextStyle",
        "import androidx.compose.ui.text.font.FontFamily",
        "import androidx.compose.ui.text.font.FontWeight",
        "import androidx.compose.ui.unit.dp",
        "import androidx.compose.ui.unit.em",
        "import androidx.compose.ui.unit.sp",
        "",
    ]
    L += ["/** Wingtip's colours: the chart's, the flight categories', the mark's; each also as", " *  the hex a MapLibre style takes. */"]
    L.append("object WingtipColors {")
    for group in SHARED:
        L.append("    object %s {" % group.capitalize())
        for k, t in tokens(lookup(tree, "color." + group)).items():
            c = rgba(css_value(tree, t["$value"]))
            if "$description" in t:
                L.append("        /** %s */" % t["$description"].replace("*/", "* /"))
            L.append("        val %s = %s" % (pascal(k), kt_colour(c)))
            L.append('        const val %s_HEX = "%s"' % (k.replace("-", "_").upper(), hex6(c)))
        L.append("    }")
    L += ["}", ""]
    L.append("/** One scheme's surfaces, words and states, as the web's cascade resolves them. */")
    L.append("@Immutable")
    L.append("class WingtipPalette(")
    L += ["    val %s: Color," % camel(n) for n in names]
    L.append(")")
    L.append("")
    L.append("object WingtipPalettes {")
    for s, cols in sch.items():
        L.append("    val %s = WingtipPalette(" % pascal(s))
        for n in names:
            c = cols.get(n)
            L.append("        %s = %s," % (camel(n), kt_colour(c) if c else "Color.Unspecified"))
        L.append("    )")
    L.append("}")
    L.append("")
    L += system.kotlin(sch, names, camel)
    L.append("/** The text roles in Material's type scale, sizes in sp so they follow the")
    L.append(" *  phone's font size. */")
    slots = {}
    for k, r in tokens(tree["type"]).items():
        # A slot's name alone takes the role's own size; an object names
        # the slot and Material 3's size for it, which wins.
        android = r.get("$extensions", {}).get(EXT, {}).get("android")
        if isinstance(android, dict):
            slots[android["slot"]] = {**r["$value"], **{k: v for k, v in android.items() if k != "slot"}}
        elif android:
            slots[android] = r["$value"]
    L += typography.kotlin(slots)
    for obj, group in (("WingtipSpace", "space"), ("WingtipRadius", "radius")):
        L.append("object %s {" % obj)
        for k, t in tokens(tree[group]).items():
            L.append("    val %s = %g.dp" % (pascal(k), t["$value"]))
        L.append("}")
        L.append("")
    L.append("/** Motion: durations in milliseconds, curves as easings. */")
    L.append("object WingtipMotion {")
    for k, t in tokens(tree["motion"]).items():
        v = t["$value"]
        if isinstance(v, list):
            L.append("    val %s = CubicBezierEasing(%s)" % (pascal(k), ", ".join("%gf" % x for x in v)))
        else:
            L.append("    const val %s_MS = %d" % (re.sub("-", "_", k).upper(), round(v * 1000)))
    L.append("}")
    L.append("")
    L += haptic.kotlin(tokens(tree["haptic"])) + [flow.kotlin(tree), ""]
    L.append("object WingtipSize {")
    for k, t in tokens(tree["size"]).items():
        v = t.get("$extensions", {}).get(EXT, {}).get("android", t["$value"])
        L.append("    val %s = %g.dp" % (pascal(k), v))
    L.append("}")
    return "\n".join(L) + "\n"


# ---------------------------------------------------------------- main


def main():
    check = "--check" in sys.argv[1:]
    tree = json.loads(SOURCE.read_text())
    sch = schemes(tree)
    outputs = {
        WEB_CSS: gen_css(tree),
        WEB_TS: gen_ts(tree),
        IOS_SWIFT: gen_swift(tree, sch),
        ANDROID_KT: gen_kotlin(tree, sch),
        FORMATS: gen_formats(tokens(tree["format"]), camel, BANNER),
    }
    stale = []
    for path, text in outputs.items():
        old = path.read_text() if path.exists() else None
        if old == text:
            continue
        if check:
            stale.append(path.relative_to(ROOT))
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(text)
            print("wrote %s" % path.relative_to(ROOT))
    if stale:
        print("design tokens out of date -- run scripts/build/design-tokens.sh and commit:", file=sys.stderr)
        for p in stale:
            print("  %s" % p, file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
