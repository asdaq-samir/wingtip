# ---------------------------------------------------------------- reading


def tokens(group):
    """A group's own tokens, name to token, in the file's order."""
    return {k: v for k, v in group.items() if not k.startswith("$") and isinstance(v, dict) and "$value" in v}


def lookup(tree, path):
    node = tree
    for part in path.split("."):
        node = node[part]
    return node


ALIAS = re.compile(r"^\{([\w.-]+)\}$")


def css_value(tree, value):
    """A colour as the stylesheet writes it: an alias into the theme or a
    look becomes var(--name), so it follows the scheme as the cascade
    does; one to anything else is that token's own value."""
    m = ALIAS.match(value)
    if not m:
        return value
    path = m.group(1)
    if path.startswith(("color.theme.", "color.look.")):
        return "var(--%s)" % path.rsplit(".", 1)[1]
    return css_value(tree, lookup(tree, path)["$value"])


# ---------------------------------------------------------------- colour


def _srgb_encode(c):
    return 12.92 * c if c <= 0.0031308 else 1.055 * c ** (1 / 2.4) - 0.055


def rgba(value):
    """A CSS colour (hex, rgb(), oklch(), transparent) as 0-255 r, g, b and
    an alpha 0-1, as a browser renders it in sRGB (oklch through OKLab,
    Björn Ottosson's matrices; out-of-gamut channels clipped)."""
    v = value.strip().lower()
    if v == "transparent":
        return (0, 0, 0, 0.0)
    if v.startswith("#"):
        h = v[1:]
        if len(h) in (3, 4):
            h = "".join(ch * 2 for ch in h)
        r, g, b = int(h[0:2], 16), int(h[2:4], 16), int(h[4:6], 16)
        a = int(h[6:8], 16) / 255 if len(h) == 8 else 1.0
        return (r, g, b, a)
    m = re.match(r"^(rgb|oklch)\(\s*([^)/]+?)\s*(?:/\s*([\d.]+%?))?\s*\)$", v)
    if not m:
        raise ValueError("not a colour: %s" % value)
    kind, body, alpha = m.groups()
    a = 1.0
    if alpha:
        a = float(alpha[:-1]) / 100 if alpha.endswith("%") else float(alpha)
    parts = [float(p) for p in body.split()]
    if kind == "rgb":
        return (round(parts[0]), round(parts[1]), round(parts[2]), a)
    L, C, H = parts
    la, lb = C * math.cos(math.radians(H)), C * math.sin(math.radians(H))
    l_ = (L + 0.3963377774 * la + 0.2158037573 * lb) ** 3
    m_ = (L - 0.1055613458 * la - 0.0638541728 * lb) ** 3
    s_ = (L - 0.0894841775 * la - 1.2914855480 * lb) ** 3
    lin = (
        4.0767416621 * l_ - 3.3077115913 * m_ + 0.2309699292 * s_,
        -1.2684380046 * l_ + 2.6097574011 * m_ - 0.3413193965 * s_,
        -0.0041960863 * l_ - 0.7034186147 * m_ + 1.7076147010 * s_,
    )
    r, g, b = (round(max(0.0, min(1.0, _srgb_encode(max(0.0, c)))) * 255) for c in lin)
    return (r, g, b, a)


def hex6(c):
    return "#%02x%02x%02x" % c[:3]


# ---------------------------------------------------------------- schemes


def theme_group(tree, *path):
    try:
        return tokens(lookup(tree, ".".join(path)))
    except KeyError:
        return {}


def schemes(tree):
    """Each scheme's colours as the web's cascade resolves them: the theme
    under its look, the night over the day, every var() followed. The
    phones take these whole."""
    light = theme_group(tree, "color", "theme", "light")
    dark = theme_group(tree, "color", "theme", "dark")
    sun = theme_group(tree, "color", "theme", "sunlight")
    layers = {
        "light": [light],
        "dark": [light, dark],
        "sunlight": [light, sun],
        "cockpitLight": [light, theme_group(tree, "color", "look", "cockpit", "light")],
        "cockpitDark": [light, dark, theme_group(tree, "color", "look", "cockpit", "dark")],
        "inkLight": [
            light,
            theme_group(tree, "color", "look", "ink", "all"),
            theme_group(tree, "color", "look", "ink", "light"),
            theme_group(tree, "color", "material", "ink", "light"),
        ],
        "inkDark": [
            light,
            dark,
            theme_group(tree, "color", "look", "ink", "all"),
            theme_group(tree, "color", "look", "ink", "dark"),
            theme_group(tree, "color", "material", "ink", "dark"),
        ],
    }
    out = {}
    for name, stack in layers.items():
        raw = {}
        for layer in stack:
            for k, t in layer.items():
                raw[k] = css_value(tree, t["$value"])

        def resolve(v, depth=0):
            m = re.match(r"^var\(--([\w-]+)\)$", v)
            return resolve(raw[m.group(1)], depth + 1) if m and depth < 8 else v

        out[name] = {k: rgba(resolve(v)) for k, v in raw.items()}
    return out


def all_names(sch):
    names = []
    for s in sch.values():
        for k in s:
            if k not in names:
                names.append(k)
    return names


def camel(name):
    head, *rest = re.split(r"[-_]", name)
    return head + "".join(p[:1].upper() + p[1:] for p in rest)


def pascal(name):
    c = camel(name)
    return c[:1].upper() + c[1:]


def flat_colours(tree, group):
    return {k: rgba(css_value(tree, t["$value"])) for k, t in tokens(lookup(tree, group)).items()}


# ---------------------------------------------------------------- web


def rem(px):
    return ("%.4f" % (px / 16)).rstrip("0").rstrip(".") + "rem"


def css_block(selector, decls):
    lines = ["%s {" % selector]
    lines += ["  --%s: %s;" % (k, v) for k, v in decls]
    lines.append("}")
    return "\n".join(lines)


def font_stack(tree, path):
    return ", ".join(f if f in ("sans-serif", "serif", "monospace") else "'%s'" % f for f in lookup(tree, path)["$value"])


def gen_css(tree):
    def decls(*path):
        return [(k, css_value(tree, t["$value"])) for k, t in theme_group(tree, *path).items()]

    radius = {k: t["$value"] for k, t in tokens(tree["radius"]).items()}
    space = {k: t["$value"] for k, t in tokens(tree["space"]).items()}
    mat = {k: t["$value"] for k, t in tokens(tree["material"]).items()}
    motion = {k: t["$value"] for k, t in tokens(tree["motion"]).items()}

    def bezier(v):
        return "cubic-bezier(%s)" % ", ".join("%g" % x for x in v)

    root = [("display", "var(--font-sans)"), ("radius", rem(radius["base"])), ("spacing", rem(space["unit"]))]
    root += [("space-%s" % k, rem(v)) for k, v in space.items() if k != "unit"]
    root += [("radius-card", rem(radius["card"])), ("radius-dialog", "%gpx" % radius["dialog"]), ("radius-sheet", "%gpx" % radius["sheet"])]
    root += [
        ("glass-blur", "%gpx" % mat["glass-blur"]),
        ("glass-fill-light", "%g%%" % (mat["glass-fill"] * 100)),
        ("glass-fill-dark", "%g%%" % (mat["glass-fill-dark"] * 100)),
        ("sheet-blur", "%gpx" % mat["sheet-blur"]),
    ]
    root += [("motion-%s" % k, bezier(v) if isinstance(v, list) else "%gs" % v) for k, v in motion.items()]
    root += [("tap-target", "%gpx" % tree["size"]["tap-target"]["$value"])]
    root += [("size-%s" % k, "%gpx" % t["$value"]) for k, t in tokens(tree["size"]).items() if k != "tap-target"]
    root += decls("color", "theme", "light")
    ink_all = [
        ("brand-font", font_stack(tree, "font.brand").rsplit(",", 1)[0]),
        ("display", font_stack(tree, "font.display")),
        ("radius", rem(radius["ink"])),
    ] + decls("color", "look", "ink", "all")
    blocks = [
        "/* %s */" % BANNER,
        "/* The ground every look builds on, by day. */\n" + css_block(":root", root),
        "/* Night (the cockpit's navy). */\n" + css_block(".dark", decls("color", "theme", "dark")),
        "/* Wingtip, the default look: the theme's own blue, in the looks' typeface. */\n"
        + css_block(':root[data-brand="wingtip"]', [("brand-font", font_stack(tree, "font.brand").rsplit(",", 1)[0])]),
        "/* Glass Cockpit: what can be tapped, the typeface and the corners.\n"
        "   :not(.dark) and .dark each, so a look's day never wins over the night. */\n"
        + css_block(
            ':root[data-brand="cockpit"]',
            [("brand-font", font_stack(tree, "font.brand").rsplit(",", 1)[0]), ("radius", rem(radius["cockpit"]))],
        ),
        css_block(':root[data-brand="cockpit"]:not(.dark)', decls("color", "look", "cockpit", "light")),
        css_block(':root.dark[data-brand="cockpit"]', decls("color", "look", "cockpit", "dark")),
        "/* Chart ink, not in sunlight, whose own tokens win. */\n" + css_block(':root[data-brand="ink"]', ink_all),
        css_block(':root[data-brand="ink"]:not(.dark):not([data-chart-light="bright"])', decls("color", "look", "ink", "light")),
        css_block(':root.dark[data-brand="ink"]:not([data-chart-light="bright"])', decls("color", "look", "ink", "dark")),
        "/* Sunlight, over day, night and every look. */\n"
        + css_block(':root[data-chart-light="bright"],\n:root.dark[data-chart-light="bright"]', decls("color", "theme", "sunlight")),
    ]
    return "\n\n".join(blocks) + "\n"


TAILWIND_SIZES = {12: "text-xs", 14: "text-sm", 16: "text-base", 18: "text-lg", 20: "text-xl"}


def web_class(role):
    """A role's Tailwind classes, as lib/text.ts used them: the touch size
    with its leading where the mouse's is the same; else the mouse's
    named size (whose leading index.css sets on a touch screen) with the
    touch size beside it. The face, case, spacing and digits come with
    the label, word and figure, and their weight with them; the other
    roles leave the weight to the words they are on."""
    v = role["$value"]
    web = role.get("$extensions", {}).get(EXT, {}).get("web", {})
    out = []
    styled = "textCase" in v or v.get("tabular")
    if "{font.display}" == v.get("fontFamily"):
        out.append("font-display")
    if "fontSize" in v:
        size, lead = v["fontSize"], v.get("lineHeight")
        mouse = web.get("mouse")
        if mouse is None or mouse == size:
            out.append("text-[%s]" % rem(size))
            if lead:
                out.append("leading-[%s]" % rem(lead))
        else:
            out.append(TAILWIND_SIZES.get(mouse, "text-[%s]" % rem(mouse)))
            out.append("pointer-coarse:text-[%s]" % rem(size))
            if web.get("touchLeading") and lead:
                out.append("pointer-coarse:leading-[%s]" % rem(lead))
    if styled:
        out.append({400: "font-normal", 500: "font-medium", 600: "font-semibold", 700: "font-bold"}[v["fontWeight"]])
    if v.get("textCase") == "uppercase":
        out.append("uppercase")
    if "letterSpacing" in v:
        out.append("tracking-[%gem]" % v["letterSpacing"])
    if v.get("tabular"):
        out.append("tabular-nums")
    return " ".join(out)


def ts_obj(d, indent="  "):
    return "{\n" + "".join("%s%s: %s,\n" % (indent, k, v) for k, v in d.items()) + "}"


def gen_ts(tree):
    q = json.dumps
    chart = {camel(k): q(hex6(c)) for k, c in flat_colours(tree, "color.chart").items()}
    cats = flat_colours(tree, "color.category")
    # The four categories; a "-chip" token is one's fill under white words.
    cat = {k.upper(): q(hex6(c)) for k, c in cats.items() if "-" not in k and k != "unknown"}
    chip = {k.upper(): q(hex6(cats.get(k + "-chip", c))) for k, c in cats.items() if "-" not in k and k != "unknown"}
    brand = {camel(k): q(hex6(c)) for k, c in flat_colours(tree, "color.brand").items()}
    ink = {
        camel(k): q(css_value(tree, t["$value"]))
        for k, t in theme_group(tree, "color", "look", "ink", "all").items()
        if k.startswith("ink-")
    }
    roles = tokens(tree["type"])
    classes = {(camel(k) if "-" in k else k): q(web_class(r)) for k, r in roles.items()}
    points = {camel(k): r["$value"]["fontSize"] for k, r in roles.items() if "fontSize" in r["$value"]}
    motion = {camel(k): (q(t["$value"]) if isinstance(t["$value"], list) else t["$value"]) for k, t in tokens(tree["motion"]).items()}
    radius = {camel(k): t["$value"] for k, t in tokens(tree["radius"]).items()}
    space = {camel(k): t["$value"] for k, t in tokens(tree["space"]).items()}
    parts = [
        "/* %s */" % BANNER,
        "/** The chart's own colours, as values for what a stylesheet does not reach (a map layer's paint, a marker's html). */\n"
        "export const CHART = %s;" % ts_obj(chart),
        "/** The FAA's flight categories (AIM 7-1-7). */\nexport const CATEGORY: Record<string, string> = %s;" % ts_obj(cat),
        "/** Each category as a chip's fill under white words: the map's colour, or a deeper one where that is under 4.5:1 (LIFR). */\n"
        "export const CATEGORY_CHIP: Record<string, string> = %s;" % ts_obj(chip),
        "/** A field with no report: unknown, not fine. */\nexport const CATEGORY_UNKNOWN = %s;"
        % q(hex6(flat_colours(tree, "color.category")["unknown"])),
        "/** Wingtip's mark. */\nexport const BRAND = %s;" % ts_obj(brand),
        "/** Chart ink's own inks by day (index.css's --ink-*), for where the stylesheet is not loaded. */\nexport const INK = %s;"
        % ts_obj(ink),
        "/** Each text role's classes (lib/text's TEXT reads these). */\nexport const TYPE_CLASS = %s as const;" % ts_obj(classes),
        "/** Each text role's size in points on a touch screen, for text drawn in points (an SVG). */\n"
        "export const TYPE_POINTS = %s as const;" % ts_obj(points),
        "/** Motion: durations in seconds, curves as cubic-bezier points. */\nexport const MOTION = %s as const;" % ts_obj(motion),
        haptic.ts(tokens(tree["haptic"]), camel),
        "/** Corners, in points. */\nexport const RADIUS = %s as const;" % ts_obj(radius),
        "/** The spacing scale, in points. */\nexport const SPACE = %s as const;" % ts_obj(space),
        "/** The least hit area, in points (Apple's HIG). */\nexport const TAP_TARGET = %d;" % tree["size"]["tap-target"]["$value"],
        "/** Sizes, in points: a chip's height, the map panel's widths and the desktop's least width. */\nexport const SIZE = %s as const;"
        % ts_obj({camel(k): t["$value"] for k, t in tokens(tree["size"]).items()}),
    ]
    return "\n\n".join(parts) + "\n"


