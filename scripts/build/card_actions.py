#!/usr/bin/env python3
"""Generate each app's card action table, and its doc, from design/card-actions.json.

Each kind of card's actions, in order, with one label and one glyph per
action, were written by hand in the web, iOS and Android and had drifted
(round 6's common audit, N3, 2026-11-27): an airport row of three on one
phone, a set only the web had, labels typed in each app. They are now
written once and generated into each platform in its own idiom, as the
words (wording.py) and the tokens are: a TypeScript object for the web, a
Swift enum for iOS, a Kotlin enum for Android, and the card table in
docs/design/icons.md. Each app keeps only its wiring: what a tap does.

Checked as it is generated, so a slip fails here rather than in an app:

- every action's `wording` is a key of design/wording.json, so its label
  is the generated wording's on all three;
- every action's `glyph` is a concept of docs/design/icons.md's table,
  which each app draws from its own (ICON, WingtipIcon, WingtipIcons);
- every card lists only actions the file names, each once, and an app a
  card is drawn on gets every action that card lists.

Standard library only; run it through scripts/build/card-actions.sh, which
CI runs with --check.

Usage: card_actions.py [--check]
"""

import json
import re
import sys
from pathlib import Path

from emit import write_or_check

ROOT = Path(__file__).resolve().parents[2]
SOURCE = ROOT / "design" / "card-actions.json"
WORDING = ROOT / "design" / "wording.json"
WEB_TS = ROOT / "apps/web/src/lib/generated/cardActions.ts"
IOS_SWIFT = ROOT / "apps/ios/Wingtip/Design/Generated/CardActions.swift"
ANDROID_KT = ROOT / "apps/android/app/src/main/kotlin/app/wingtipmaps/android/design/generated/CardActions.kt"
DOC = ROOT / "docs" / "design" / "icons.md"
DOC_BEGIN = "<!-- BEGIN generated from design/card-actions.json by scripts/build/card-actions.sh -->"
DOC_END = "<!-- END generated card actions -->"

BANNER = "Generated by scripts/build/card-actions.sh from design/card-actions.json -- do not edit; change the actions and run it again."
APPS = ("web", "ios", "android")


def concepts(doc):
    """The concepts of icons.md's table, its rows' first cells."""
    table = doc.split("## Concepts", 1)[1].split("\n## ", 1)[0]
    return set(re.findall(r"^\| ([a-z][A-Za-z]*) \|", table, re.MULTILINE))


def load():
    spec = json.loads(SOURCE.read_text())
    words = json.loads(WORDING.read_text())["words"]
    glyphs = concepts(DOC.read_text())
    actions, cards = spec["actions"], spec["cards"]
    errors = []
    for name, action in actions.items():
        if action["wording"] not in words:
            errors.append(f"action {name}: wording {action['wording']!r} is not in design/wording.json")
        if action["glyph"] not in glyphs:
            errors.append(f"action {name}: glyph {action['glyph']!r} is not a concept in docs/design/icons.md")
        errors += [f"action {name}: no app {a!r}" for a in action.get("apps", []) if a not in APPS]
    for kind, card in cards.items():
        listed = card["actions"]
        errors += [f"card {kind}: no action {a!r}" for a in listed if a not in actions]
        if len(set(listed)) != len(listed):
            errors.append(f"card {kind}: an action is listed twice")
        errors += [f"card {kind}: no app {a!r}" for a in card.get("apps", []) if a not in APPS]
        for app in card.get("apps", APPS):
            missing = [a for a in listed if a in actions and app not in actions[a].get("apps", APPS)]
            errors += [f"card {kind}: {a} is not generated for {app}" for a in missing]
    if errors:
        raise SystemExit("\n".join(f"design/card-actions.json: {e}" for e in errors))
    return actions, cards, words


def for_app(actions, cards, app):
    """The cards an app draws, and the actions they and the app's own menus use, in the file's order."""
    kinds = {k: c for k, c in cards.items() if app in c.get("apps", APPS)}
    used = {a for c in kinds.values() for a in c["actions"]}
    names = [n for n, a in actions.items() if n in used or app in a.get("apps", ())]
    return names, kinds


def camel(key):
    head, *rest = key.split("_")
    return head + "".join(part.capitalize() for part in rest)


def constant(name):
    return re.sub(r"([A-Z])", r"_\1", name).upper()


def web(actions, cards):
    names, kinds = for_app(actions, cards, "web")
    rows = "\n".join(
        f"  /** {actions[n]['about']} */\n  {n}: {{ label: WORDING.{camel(actions[n]['wording'])}, icon: ICON.{actions[n]['glyph']} }},"
        for n in names
    )
    sets = "\n".join(f"  /** {c['about']} */\n  {k}: [{', '.join(json.dumps(a) for a in c['actions'])}]," for k, c in kinds.items())
    return f"""/* {BANNER} */

import {{ ICON }} from "../icons";
import {{ WORDING }} from "../wording/generated/wording";

/** Each action's one label (the generated wording) and one glyph (docs/design/icons.md) on every card and app. */
export const ACTION = {{
{rows}
}} as const;

type ActionName = keyof typeof ACTION;

/** The actions each kind of card offers, in order; the first is its filled one. */
export const CARD_ACTIONS = {{
{sets}
}} as const satisfies Record<string, readonly ActionName[]>;
"""


def ios(actions, cards):
    names, kinds = for_app(actions, cards, "ios")
    cases = "\n".join(f"    /// {actions[n]['about']}\n    case {n}" for n in names)
    titles = "\n".join(f"        case .{n}: Wording.{camel(actions[n]['wording'])}" for n in names)
    images = "\n".join(f"        case .{n}: WingtipIcon.{actions[n]['glyph']}" for n in names)
    kind_cases = "\n".join(f"    /// {c['about']}\n    case {k}" for k, c in kinds.items())
    kind_sets = "\n".join(f"        case .{k}: [{', '.join('.' + a for a in c['actions'])}]" for k, c in kinds.items())
    return f"""// {BANNER}

import Foundation

/// A card's action, one label (the generated wording) and one glyph (the
/// shared concept table's, WingtipIcon; docs/design/icons.md) on every card
/// and app.
enum CardAction: String, CaseIterable, Sendable {{
{cases}

    var title: String {{
        switch self {{
{titles}
        }}
    }}

    var systemImage: String {{
        switch self {{
{images}
        }}
    }}
}}

/// The kinds of card, each with its actions in order; the first is its
/// filled one.
enum CardKind: String, CaseIterable, Sendable {{
{kind_cases}

    var actions: [CardAction] {{
        switch self {{
{kind_sets}
        }}
    }}
}}
"""


def android(actions, cards):
    names, kinds = for_app(actions, cards, "android")
    entry = "    /** {about} */\n    {name}(R.string.wording_{wording}, WingtipIcons.{glyph}),"
    rows = "\n".join(entry.format(name=constant(n), **actions[n]) for n in names)
    sets = "\n".join(
        f"    /** {c['about']} */\n    {constant(k)}(listOf({', '.join('CardAction.' + constant(a) for a in c['actions'])})),"
        for k, c in kinds.items()
    )
    return f"""// {BANNER}

package app.wingtipmaps.android.design.generated

import androidx.annotation.StringRes
import androidx.compose.ui.graphics.vector.ImageVector
import app.wingtipmaps.android.R
import app.wingtipmaps.android.ui.WingtipIcons

/** A card's action, one label (the generated wording) and one glyph (the
 *  shared concept table's, WingtipIcons; docs/design/icons.md) on every
 *  card and app. */
enum class CardAction(@StringRes val label: Int, val icon: ImageVector) {{
{rows}
}}

/** The kinds of card, each with its actions in order; the first is its
 *  filled one. */
enum class CardKind(val actions: List<CardAction>) {{
{sets}
}}
"""


def doc_block(actions, cards, words):
    label = {n: words[a["wording"]]["text"] for n, a in actions.items()}
    rows = [
        f"| `{k}` | {', '.join(label[a] for a in c['actions'])} | {', '.join(c.get('apps', APPS))} | {c['about']} |"
        for k, c in cards.items()
    ]
    terms = [f"- **{label[n]}** (`{n}`, glyph `{a['glyph']}`): {a['about']}" for n, a in actions.items()]
    head = [DOC_BEGIN, "", "| Card | Actions, in order | Apps | Which |", "|---|---|---|---|"]
    return "\n".join(head + rows + [""] + terms + ["", DOC_END])


def doc(block, current):
    """icons.md with its generated block replaced, the rest of it as written."""
    span = re.compile(re.escape(DOC_BEGIN) + ".*?" + re.escape(DOC_END), re.DOTALL)
    if not span.search(current):
        raise SystemExit(f"{DOC.relative_to(ROOT)}: no {DOC_BEGIN!r} ... {DOC_END!r} block to fill")
    return span.sub(lambda _: block, current, count=1)


def main():
    actions, cards, words = load()
    outputs = {WEB_TS: web(actions, cards), IOS_SWIFT: ios(actions, cards), ANDROID_KT: android(actions, cards)}
    outputs[DOC] = doc(doc_block(actions, cards, words), DOC.read_text())
    return write_or_check(outputs, ROOT, "design/card-actions.json", "scripts/build/card-actions.sh")


if __name__ == "__main__":
    sys.exit(main())
