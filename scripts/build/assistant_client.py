"""The assistant's generated code, from the two documents it rests on, and
the check that what is committed is what they make (the owner's rule of
2026-11-09: what can be generated is never hand-written).

From the planner's OpenAPI document (services/planner/openapi.json):

- services/assistant/app/generated/planner_models.py: a pydantic model of
  every schema, by datamodel-code-generator. Every field is optional
  (--force-optional): the assistant copes with a field missing and reads
  the rest by name, so a field renamed in the planner is an attribute
  that no longer exists, not a .get() that quietly answers None.
- services/assistant/app/generated/planner_client.py: one function per
  operation answering JSON, its path, query, header and body parameters
  typed from the document and its answer validated into the models.
- services/planner/app/generated/planner_calls.py: the same operations as
  async functions over the planner's own app, for its MCP connector's
  tools (scripts/build/planner_calls.py).

From the engine's contract (engine/contract/engine.schema.json):

- services/assistant/app/generated/engine_tools.py: each rule tagged
  "x-tool": true as a Claude tool (its name, its description with the
  CFR or AIM paragraph it rests on, its input schema with the contract's
  definitions written in), asked through the planner (issue #569).
- services/planner/app/generated/engine_tools.py: the same names and
  those tagged "x-assistant": true (rules the assistant asks for its own
  checks, not the pilot's tools: a photographed page's figures), the
  allow-list of the planner's POST /api/engine/{name}.

    python scripts/build/assistant_client.py           # write them
    python scripts/build/assistant_client.py --check   # fail if they differ

scripts/build/assistant-client.sh runs it in Docker with the pinned
datamodel-code-generator; services/assistant/tests/test_generated.py runs
--check in the assistant's suite.
"""

from __future__ import annotations

import argparse
import copy
import difflib
import json
import keyword
import re
import subprocess
import sys
import tempfile
import types
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
PLANNER_SPEC = ROOT / "services/planner/openapi.json"
CONTRACT = ROOT / "engine/contract/engine.schema.json"
ASSISTANT_OUT = ROOT / "services/assistant/app/generated"
PLANNER_OUT = ROOT / "services/planner/app/generated"

HEADER = (
    "# GENERATED by scripts/build/assistant_client.py from {source}.\n"
    "# Do not edit: change the source and run scripts/build/assistant-client.sh.\n"
    "# ruff: noqa: E501\n"
)

#: datamodel-code-generator's options: pydantic v2, Literal for enums (the
#: answers are dumped back to JSON for the model, and a Literal dumps as
#: its string), every field optional, aliases ("from") populated by name.
DATAMODEL_ARGS = (
    "--input-file-type openapi --output-model-type pydantic_v2.BaseModel --target-python-version 3.15 --disable-timestamp"
    " --formatters builtin --use-annotated --field-constraints --use-union-operator --use-standard-collections"
    " --enum-field-as-literal all --force-optional --allow-population-by-field-name"
).split()


def class_name(schema: str) -> str:
    """The class datamodel-code-generator gives a component ("VorCheck-Input"
    is VorCheckInput); generate() checks each one is there."""
    return re.sub(r"\W", "", schema)


# --- planner_models.py ------------------------------------------------------


def planner_models() -> str:
    with tempfile.TemporaryDirectory() as tmp:
        out = Path(tmp) / "planner_models.py"
        subprocess.run(
            [sys.executable, "-m", "datamodel_code_generator", "--input", str(PLANNER_SPEC), "--output", str(out), *DATAMODEL_ARGS],
            check=True,
            capture_output=True,
            text=True,
        )
        body = out.read_text()
    # Its own first lines name a temporary path; ours name the source.
    body = re.sub(r"\A(#[^\n]*\n)+\n*", "", body)
    # A model may name one defined further down: Python 3.14 reads
    # annotations late (PEP 649) and the models' rebuild at the end
    # resolves them, which Ruff's F821 does not know.
    return (
        HEADER.format(source="services/planner/openapi.json").replace("E501", "E501, F821")
        + '"""The planner\'s schemas as pydantic models, every field optional."""\n\n'
        + body
    )


# --- planner_client.py ------------------------------------------------------


def _py_type(schema: dict, spec: dict) -> str:
    """A JSON schema as a Python annotation over the models (m.)."""
    if not schema:
        return "Any"
    if "$ref" in schema:
        return "m." + class_name(schema["$ref"].rsplit("/", 1)[-1])
    for key in ("anyOf", "oneOf"):
        if key in schema:
            parts = list(dict.fromkeys(_py_type(s, spec) for s in schema[key]))
            return "Any" if "Any" in parts else " | ".join(parts)
    if "enum" in schema:
        return "Literal[" + ", ".join(repr(v) for v in schema["enum"]) + "]"
    if "const" in schema:
        return f"Literal[{schema['const']!r}]"
    kind = schema.get("type")
    if isinstance(kind, list):
        return " | ".join(_py_type({**schema, "type": k}, spec) for k in kind)
    if kind == "array":
        return f"list[{_py_type(schema.get('items') or {}, spec)}]"
    if kind == "object":
        extra = schema.get("additionalProperties")
        return f"dict[str, {_py_type(extra, spec) if isinstance(extra, dict) else 'Any'}]"
    return {"string": "str", "number": "float", "integer": "int", "boolean": "bool", "null": "None"}.get(kind, "Any")


def _ident(name: str) -> str:
    out = re.sub(r"\W", "_", name).lower()
    return out + "_" if keyword.iskeyword(out) else out


def _function_name(op_id: str, path: str, method: str, taken: set[str]) -> str:
    """FastAPI's operationId is the route function's name, the path and the
    method run together; the function's name alone, where it is unique."""
    suffix = re.sub(r"\W", "_", path) + "_" + method
    name = op_id[: -len(suffix)] if op_id.endswith(suffix) else op_id
    return op_id if name in taken or not name.isidentifier() else name


def _operations(spec: dict):
    for path, ops in sorted(spec["paths"].items()):
        for method, op in sorted(ops.items()):
            if method not in ("get", "post", "put", "delete"):
                continue
            ok = op.get("responses", {}).get("200", {}).get("content", {})
            if "application/json" not in ok:
                continue  # a tile, a file, a stream: not an answer to read
            yield path, method, op


def planner_client(spec: dict) -> str:
    lines: list[str] = []
    taken: set[str] = set()
    for path, method, op in _operations(spec):
        fn = _function_name(op["operationId"], path, method, taken)
        taken.add(fn)
        params = op.get("parameters", [])
        args, query, headers, path_args = [], [], [], {}
        for p in sorted(params, key=lambda p: not p.get("required")):
            arg = _ident(p["name"])
            annotation = _py_type(p.get("schema") or {}, spec)
            if p.get("required"):
                args.append(f"{arg}: {annotation}")
            else:
                args.append(
                    f"{arg}: {annotation} | None = None" if "None" not in annotation.split(" | ") else f"{arg}: {annotation} = None"
                )
            if p["in"] == "query":
                query.append(f"{p['name']!r}: {arg}")
            elif p["in"] == "header":
                headers.append(f"{p['name']!r}: {arg}")
            elif p["in"] == "path":
                path_args[p["name"]] = arg
        body = op.get("requestBody", {}).get("content", {}).get("application/json", {}).get("schema")
        if body is not None:
            body_type = _py_type(body, spec)
            body_type = body_type if body_type.startswith("dict[") else f"{body_type} | dict[str, Any]"
            required = op["requestBody"].get("required", False)
            args.insert(0, f"body: {body_type}" if required else f"body: {body_type} | None = None")
        answer = _py_type(ok_schema(op), spec)
        url = re.sub(r"\{([^}]+)\}", lambda m: "{_seg(" + path_args[m.group(1)] + ")}", path)
        url = f'f"{url}"' if path_args else repr(url)
        doc = (op.get("summary") or op["operationId"]).strip()
        lines += [
            "",
            f"_{fn.upper()} = _Answer({answer})",
            "",
            "",
            f"def {fn}({'*, ' if args else ''}{', '.join(args)}) -> {answer}:",
            f'    """{method.upper()} {path}: {doc}"""',
            f"    found = _send({method.upper()!r}, {url}, query={{{', '.join(query)}}}, "
            f"body={'_body(body)' if body is not None else 'None'}, headers={{{', '.join(headers)}}})",
            f"    return _{fn.upper()}.validate_python(found)",
            "",
        ]
    return HEADER.format(source="services/planner/openapi.json") + CLIENT_HEAD + "\n".join(lines).rstrip() + "\n"


def ok_schema(op: dict) -> dict:
    return op["responses"]["200"]["content"]["application/json"].get("schema") or {}


CLIENT_HEAD = '''"""The planner's HTTP API as functions, one per operation answering JSON,
each answer validated into the planner's own models (planner_models). The
assistant computes nothing a pilot reads as a figure: everything comes
from here. A refusal -- an ident that is not one, a route with no legal
altitude -- is PlannerError with the planner's own status and words, and
an answer not of the planner's documented shape is a PlannerError too
(502), so the drift is said where it happens."""
from __future__ import annotations

from typing import Any, Literal  # noqa: F401 -- Literal is used where an operation has an enum
from urllib.parse import quote

import requests
from pydantic import BaseModel, TypeAdapter, ValidationError

from ..settings import get_settings
from . import planner_models as m  # noqa: F401


class PlannerError(Exception):
    """The planner said no, or could not be reached: its status (502
    where it never answered) and its words."""

    def __init__(self, status: int, detail: str):
        super().__init__(detail)
        self.status = status
        self.detail = detail


def _detail(resp: requests.Response) -> str:
    try:
        detail = resp.json().get("detail")
    except (ValueError, AttributeError):
        detail = None
    if isinstance(detail, list):
        # FastAPI's 422: each field and what is wrong with it.
        return "; ".join(f"{'.'.join(str(p) for p in d.get('loc', [])[1:])}: {d.get('msg')}" for d in detail if isinstance(d, dict))
    return str(detail) if detail else f"the planner answered {resp.status_code}"


def _seg(value: Any) -> str:
    """A path parameter as one segment, so a stray slash cannot reach
    another path."""
    return quote(str(value), safe="")


def _body(body: Any) -> Any:
    """A model as the JSON it was given (unset fields left out, aliases
    as the planner names them); a dict as it is."""
    return body.model_dump(mode="json", by_alias=True, exclude_unset=True) if isinstance(body, BaseModel) else body


def _send(method: str, path: str, *, query: dict | None = None, body: Any = None, headers: dict | None = None) -> Any:
    """One call: the planner's JSON answer, or PlannerError. None and ""
    are left out of a query, as the planner reads an absent field."""
    settings = get_settings()
    params = {k: v for k, v in (query or {}).items() if v is not None and v != ""}
    sent = {k: v for k, v in (headers or {}).items() if v is not None} or None
    try:
        resp = requests.request(method, settings.planner_url + path, params=params, json=body, headers=sent,
                                timeout=settings.planner_timeout_s)
    except requests.RequestException as err:
        raise PlannerError(502, f"The planner could not be reached: {type(err).__name__}") from err
    if resp.status_code >= 400:
        raise PlannerError(resp.status_code, _detail(resp))
    return resp.json()


class _Answer:
    """An operation's answer read into its type; an answer not of it is a
    PlannerError, the planner and its document having parted."""

    def __init__(self, annotation: Any) -> None:
        self.adapter: TypeAdapter = TypeAdapter(annotation)

    def validate_python(self, found: Any) -> Any:
        try:
            return self.adapter.validate_python(found)
        except ValidationError as err:
            raise PlannerError(502, f"The planner's answer is not of its documented shape: {err.errors()[:3]}") from err
'''


# --- engine_tools.py (assistant) and the planner's allow-list ---------------


def _inline(node, definitions: dict, seen: tuple = ()):
    """A schema with each #/definitions/ reference written in, so a tool's
    input_schema stands alone."""
    if isinstance(node, list):
        return [_inline(n, definitions, seen) for n in node]
    if not isinstance(node, dict):
        return node
    if "$ref" in node:
        name = node["$ref"].rsplit("/", 1)[-1]
        if name in seen:
            raise ValueError(f"the contract's {name} refers to itself; a tool's input cannot be written out")
        merged = {**copy.deepcopy(definitions[name]), **{k: v for k, v in node.items() if k != "$ref"}}
        return _inline(merged, definitions, (*seen, name))
    return {k: _inline(v, definitions, seen) for k, v in node.items()}


def engine_tools(contract: dict) -> list[dict]:
    """Each rule tagged "x-tool": true, as Claude's tool definition."""
    tools = []
    for name, entry in contract["properties"].items():
        if not entry.get("x-tool"):
            continue
        schema = _inline(entry["properties"]["input"], contract.get("definitions", {}))
        schema.pop("title", None)
        schema.setdefault("type", "object")
        schema.setdefault("properties", {})
        if schema["type"] != "object":
            raise ValueError(f"{name}: a tool's input is an object; the contract's is {schema['type']}")
        if not re.fullmatch(r"[a-zA-Z0-9_-]{1,64}", name):
            raise ValueError(f"{name}: not a name Claude's tools take")
        tools.append({"name": name, "description": entry["description"], "input_schema": schema})
    return tools


def assistant_engine_tools(contract: dict) -> str:
    tools = engine_tools(contract)
    return (
        HEADER.format(source="engine/contract/engine.schema.json")
        + '"""The engine\'s rules a pilot asks about, as the assistant\'s tools (#569): every\n'
        'rule the contract tags "x-tool": true, its description (with the CFR or AIM\n'
        'paragraph it rests on) and its input schema as the contract has them. The\n'
        'assistant asks each through the planner (POST /api/engine/{name})."""\n'
        "import json\n\n"
        "#: Each {name, description, input_schema}, as Claude's tool definition takes them.\n"
        "TOOLS: list[dict] = json.loads(r'''\n" + _literal(tools) + "\n''')\n"
    )


def planner_engine_names(contract: dict) -> str:
    names = [name for name, entry in contract["properties"].items() if entry.get("x-tool") or entry.get("x-assistant")]
    return (
        HEADER.format(source="engine/contract/engine.schema.json")
        + '"""The engine\'s rules the planner answers on POST /api/engine/{name}: those the\n'
        'contract tags "x-tool": true, the assistant\'s tools (#569), and "x-assistant":\n'
        'true, its own checks (a photographed page\'s figures), and no other."""\n'
        "from typing import Literal\n\n"
        "EngineToolName = Literal[\n" + "".join(f"    {n!r},\n" for n in names) + "]\n"
    )


def _literal(value) -> str:
    """A JSON value as the text of a raw string literal."""
    text = json.dumps(value, indent=2, ensure_ascii=False)
    if "'''" in text:
        raise ValueError("a description holds ''', which the generated literal cannot")
    return text


# --- all of it --------------------------------------------------------------


def generate() -> dict[Path, str]:
    from planner_calls import planner_calls  # beside this file; it imports this one's helpers

    spec = json.loads(PLANNER_SPEC.read_text())
    contract = json.loads(CONTRACT.read_text())
    models = planner_models()
    # Every model the client names is one the models file has.
    module = types.ModuleType("planner_models")
    # Registered, as an import would: pydantic 2.14 looks a generic
    # RootModel's module up in sys.modules when the class is made.
    sys.modules[module.__name__] = module
    exec(compile(models, "planner_models.py", "exec"), module.__dict__)  # noqa: S102 -- our own generated source
    client = planner_client(spec)
    missing = sorted({n for n in re.findall(r"\bm\.(\w+)", client) if not hasattr(module, n)})
    if missing:
        raise SystemExit(f"planner_client names models planner_models lacks: {missing}")
    init = '"""Generated code: see scripts/build/assistant_client.py. Do not edit."""\n'
    return {
        ASSISTANT_OUT / "__init__.py": init,
        ASSISTANT_OUT / "planner_models.py": models,
        ASSISTANT_OUT / "planner_client.py": client,
        ASSISTANT_OUT / "engine_tools.py": assistant_engine_tools(contract),
        PLANNER_OUT / "__init__.py": init,
        PLANNER_OUT / "engine_tools.py": planner_engine_names(contract),
        PLANNER_OUT / "planner_calls.py": planner_calls(spec),
    }


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    parser.add_argument("--check", action="store_true", help="fail where a committed file differs from what is generated")
    check = parser.parse_args().check
    stale = []
    for path, text in generate().items():
        have = path.read_text() if path.exists() else ""
        if have == text:
            continue
        if check:
            rel = str(path.relative_to(ROOT))
            stale.append(rel)
            sys.stdout.writelines(list(difflib.unified_diff(have.splitlines(True), text.splitlines(True), rel, rel + " (generated)"))[:40])
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(text)
            print(f"wrote {path.relative_to(ROOT)}")
    if stale:
        print("\nOut of date; run scripts/build/assistant-client.sh:\n  " + "\n  ".join(stale))
        return 1
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
