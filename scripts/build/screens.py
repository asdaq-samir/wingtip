#!/usr/bin/env python3
"""Generate each app's list of screens, and their links, from design/screens.json.

One source for the screens a link can open, written into each platform in
its own idiom: a TypeScript module for the web, a Swift enum for iOS, a
Kotlin enum for Android, and the table of links in docs/navigation.md. Each
app opens a screen in one exhaustive switch over its generated list, so a
screen added to the source fails an app's build until that app opens it,
and the three cannot name a screen differently. Standard library only, so
it needs nothing installed; run it through scripts/build/screens.sh, which
CI runs with --check.

Usage: screens.py [--check]
"""

import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
SOURCE = ROOT / "design" / "screens.json"
WEB_TS = ROOT / "apps/web/src/lib/navigation/generated/screens.ts"
IOS_SWIFT = ROOT / "apps/ios/Wingtip/Navigation/Generated/Screens.swift"
ANDROID_KT = ROOT / "apps/android/app/src/main/kotlin/app/wingtipmaps/android/navigation/generated/Screens.kt"
DOC = ROOT / "docs" / "navigation.md"
DOC_BEGIN = "<!-- BEGIN generated from design/screens.json by scripts/build/screens.sh -->"
DOC_END = "<!-- END generated -->"

BANNER = "Generated by scripts/build/screens.sh from design/screens.json -- do not edit; change the screens and run it again."
PLATFORMS = ("web", "ios", "android")


def load():
    spec = json.loads(SOURCE.read_text())
    seen = set()
    for screen in spec["screens"]:
        sid = screen["id"]
        if not re.fullmatch(r"[a-z][a-z0-9]*", sid):
            raise SystemExit(f"design/screens.json: {sid!r} is not a lower-case word (it is a URL value and a case name)")
        if sid in seen:
            raise SystemExit(f"design/screens.json: {sid!r} twice")
        seen.add(sid)
        unknown = set(screen["platforms"]) - set(PLATFORMS)
        if unknown:
            raise SystemExit(f"design/screens.json: {sid!r} names no such platform {sorted(unknown)}")
    return spec


def on(spec, platform):
    return [s for s in spec["screens"] if platform in s["platforms"]]


def quoted(text):
    return json.dumps(text, ensure_ascii=False)


def web(spec):
    link = spec["link"]
    screens = on(spec, "web")
    rows = "\n".join(f"  {s['id']}: {{ title: {quoted(s['title'])} }}," for s in screens)
    fields = ", ".join(
        f"{name}: {quoted(link[key])}"
        for name, key in (("path", "path"), ("key", "key"), ("scheme", "scheme"), ("schemeHost", "schemeHost"))
    )
    return f"""// {BANNER}

/** The link that opens a screen: the app's address with `{link['key']}` naming it. */
export const SCREEN_LINK = {{ {fields} }} as const;

/** The screens a link opens on the web, by the id the link names. */
export const SCREENS = {{
{rows}
}} as const;

export type ScreenId = keyof typeof SCREENS;

/** The screen a link's value names, or null for none the web has. */
export function screenOf(value: string | null | undefined): ScreenId | null {{
  return value && Object.hasOwn(SCREENS, value) ? (value as ScreenId) : null;
}}

/** The link to a screen, at `origin` (the site's, for a link to share). */
export function screenLink(id: ScreenId, origin = ""): string {{
  return `${{origin}}${{SCREEN_LINK.path}}?${{SCREEN_LINK.key}}=${{id}}`;
}}
"""


def ios(spec):
    link = spec["link"]
    screens = on(spec, "ios")
    cases = "\n".join(f"    case {s['id']}" for s in screens)
    titles = "\n".join(f"        case .{s['id']}: {quoted(s['title'])}" for s in screens)
    return f"""// {BANNER}

/// The screens a link opens on the iPhone and iPad, by the id the link
/// names (`{link['path']}?{link['key']}=<id>`, or `{link['scheme']}://{link['schemeHost']}?{link['key']}=<id>`).
enum Screen: String, CaseIterable, Sendable {{
{cases}

    /// The screen's title, as its row and its page name it.
    var title: String {{
        switch self {{
{titles}
        }}
    }}

    static let linkPath = {quoted(link['path'])}
    static let linkKey = {quoted(link['key'])}
    static let scheme = {quoted(link['scheme'])}
    static let schemeHost = {quoted(link['schemeHost'])}
}}
"""


def android(spec):
    link = spec["link"]
    screens = on(spec, "android")
    entries = ",\n".join(f"    {s['id'].upper()}({quoted(s['id'])}, {quoted(s['title'])})" for s in screens)
    return f"""// {BANNER}
package app.wingtipmaps.android.navigation.generated

/**
 * The screens a link opens on Android, by the id the link names
 * (`{link['path']}?{link['key']}=<id>`, or `{link['scheme']}://{link['schemeHost']}?{link['key']}=<id>`).
 */
enum class Screen(
    val id: String,
    val title: String,
) {{
{entries},
    ;

    companion object {{
        const val LINK_PATH = {quoted(link['path'])}
        const val LINK_KEY = {quoted(link['key'])}
        const val SCHEME = {quoted(link['scheme'])}
        const val SCHEME_HOST = {quoted(link['schemeHost'])}

        /** The screen a link's value names, or null for none Android has. */
        fun of(id: String?): Screen? = entries.firstOrNull {{ it.id == id }}
    }}
}}
"""


def doc_table(spec):
    link = spec["link"]
    head = [
        DOC_BEGIN,
        "",
        f"Every screen opens from `https://<host>{link['path']}?{link['key']}=<id>` (a universal link on iOS, an App Link on",
        f"Android, the address on the web) or `{link['scheme']}://{link['schemeHost']}?{link['key']}=<id>` from another app.",
        "",
        "| Link (`open=`) | Screen | Web | iOS | Android | What it is |",
        "|---|---|---|---|---|---|",
    ]
    rows = [
        f"| `{s['id']}` | {s['title']} | " + " | ".join("yes" if p in s["platforms"] else "--" for p in PLATFORMS) + f" | {s['about']} |"
        for s in spec["screens"]
    ]
    params = ["", "The plan's own keys go beside it, and alone they open what they name:", ""]
    params += [f"- `{p['key']}`: {p['about']}" for p in spec["params"]]
    return "\n".join(head + rows + params + ["", DOC_END])


def doc(spec, current):
    if DOC_BEGIN not in current or DOC_END not in current:
        raise SystemExit(f"{DOC.relative_to(ROOT)}: no {DOC_BEGIN!r} ... {DOC_END!r} block to fill")
    before, rest = current.split(DOC_BEGIN, 1)
    _, after = rest.split(DOC_END, 1)
    return before + doc_table(spec) + after


def main():
    check = "--check" in sys.argv[1:]
    spec = load()
    outputs = {WEB_TS: web(spec), IOS_SWIFT: ios(spec), ANDROID_KT: android(spec)}
    outputs[DOC] = doc(spec, DOC.read_text() if DOC.exists() else "")
    stale = []
    for path, text in outputs.items():
        now = path.read_text() if path.exists() else None
        if now == text:
            continue
        if check:
            stale.append(str(path.relative_to(ROOT)))
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(text)
            print(f"wrote {path.relative_to(ROOT)}")
    if stale:
        print("Out of date with design/screens.json (run scripts/build/screens.sh and commit):", *stale, sep="\n  ")
        sys.exit(1)


if __name__ == "__main__":
    main()
