#!/usr/bin/env python3
"""The engine rules the web app asks, from its own code, for the trimmed
WebAssembly (the owner, 2026-11-10: "Yes do it for the rules").

The web asks the engine only through `callEngine("<rule>", ...)`
(apps/web/src/lib/engine/engine.ts), and in 2026-11 it asked about 200 of
the engine's 335 rules; the rest are the planner's and the phones'. This
finds every `callEngine("<rule>"` in apps/web/src (tests too, which ask the
same module) and writes the list twice:

- engine/facade/web-rules.txt, which the facade's build script reads when
  it is built for wasm32 (engine/bindings/wasm, the web's alone), so the
  WebAssembly is built with those rules alone and the planner's wheel and
  the phones keep every rule;
- apps/web/src/lib/engine/webRules.ts, the same names as a TypeScript
  type `callEngine` takes, so a call to a rule not on the list is a type
  error, not a failure in front of a pilot; and the list `callEngine`
  checks at run time, for a name that got past the types.

A rule the web starts to ask: tsc refuses it until this is run again, then
the WebAssembly is rebuilt (scripts/build/build-engine-wasm.sh) and all
three files committed. --check only says whether the committed files are
what the code gives (the guards' "Web engine rules").

The standard library only.

  python3 scripts/build/web_rules.py [--check]
"""

import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
WEB = ROOT / "apps/web/src"
SCHEMA = ROOT / "engine/contract/engine.schema.json"
TXT = ROOT / "engine/facade/web-rules.txt"
TS = WEB / "lib/engine/webRules.ts"
# The generated files, which name every rule and ask none.
SKIP = {WEB / "lib/engine/contract.ts", TS}

# callEngine("name", ...), with its type arguments and line breaks if any.
CALL = re.compile(r'\bcallEngine\s*(?:<[^>()]*>)?\(\s*"([a-z0-9_]+)"')


def asked():
    """{rule: [files asking it]} over the web's sources."""
    found = {}
    for path in sorted(WEB.rglob("*")):
        if path.suffix not in {".ts", ".tsx"} or path in SKIP or "node_modules" in path.parts:
            continue
        text = path.read_text(encoding="utf-8")
        for m in CALL.finditer(text):
            # A call the line before marks `@ts-expect-error` is a test
            # asking past the types, for a rule the module must not have.
            before = text[: max(text.rfind("\n", 0, m.start()), 0)].rsplit("\n", 1)[-1]
            if "@ts-expect-error" in before:
                continue
            found.setdefault(m.group(1), []).append(str(path.relative_to(ROOT)))
    return found


def outputs(names):
    txt = (
        "# The engine rules the web app asks (callEngine in apps/web/src), the\n"
        "# only ones its WebAssembly is built with (the facade's web-rules\n"
        "# feature). Generated by scripts/build/web_rules.py: run it, not an edit.\n" + "".join(f"{n}\n" for n in names)
    )
    ts = (
        "/* Generated by scripts/build/web_rules.py from the web's callEngine calls: run it, not an edit. */\n"
        "\n"
        "/** The engine rules the web asks, the only ones its WebAssembly is built\n"
        " *  with (engine/facade/web-rules.txt). */\n"
        "export const WEB_RULES = [\n" + "".join(f'  "{n}",\n' for n in names) + "] as const;\n"
        "\n"
        "/** A rule the web's WebAssembly answers. */\n"
        "export type WebRule = (typeof WEB_RULES)[number];\n"
    )
    return {TXT: txt, TS: ts}


def main(argv):
    check = "--check" in argv
    found = asked()
    known = set(json.loads(SCHEMA.read_text(encoding="utf-8"))["properties"])
    # A name the contract has not is no rule to build: tsc refuses the call.
    names = sorted(set(found) & known)
    stale = []
    for path, text in outputs(names).items():
        if path.exists() and path.read_text(encoding="utf-8") == text:
            continue
        if check:
            stale.append(str(path.relative_to(ROOT)))
        else:
            path.write_text(text, encoding="utf-8")
    if stale:
        print(
            f"::error title=Web engine rules out of date::{', '.join(stale)} not what the web's callEngine calls give: "
            "run python3 scripts/build/web_rules.py, then scripts/build/build-engine-wasm.sh, and commit them."
        )
        return 1
    print(f"web engine rules: {len(names)} of the engine's {len(known)}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
