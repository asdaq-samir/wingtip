// The phones' typed calls into the engine, written from its contract
// (engine/contract/engine.schema.json) by scripts/build/engine-contract-apps.sh:
//
//   node engine-contract-apps.mjs <engine.schema.json> <swift dir> <kotlin dir>
//
// For every rule the contract names, its input and its answer become
// types (Codable structs on the iPhone, @Serializable data classes on
// Android, inside one EngineContract namespace each) and the rule becomes
// one function on Engine taking the input's members by name:
//
//   Swift:  try Engine.holdingLegMinutes(altitudeFt: 9500)      // throws Engine.Refused
//   Kotlin: Engine.holdingLegMinutes(altitudeFt = 9500.0)        // Result<Double>
//
// so a rule asked with a member it does not have, or its answer read as
// the wrong type, fails the app's build rather than reading as a default
// at runtime. The functions go through each app's one hand-written way in
// (Engine.rule, Engine.swift and Engine.kt), which logs a failure.
//
// How the contract is read, as scripts/build/api-models-apps.mjs reads
// the servers' documents:
// - Enums and consts are plain strings: an answer the engine adds a word
//   to must not fail to decode on a phone built before it.
// - Tuples are arrays of their one type.
// - A member left untyped ({}), or a union of two shapes, is OpenAPIRuntime's
//   OpenAPIValueContainer on the iPhone (as the servers' clients') and
//   kotlinx's JsonElement on Android; a union of objects told apart by a
//   const member ("kind") is one struct of every shape's members (taggedUnion).
// - Keys are written as the rule names them (snake case mostly, camel
//   case where the gateway's are): Swift's CodingKeys and Kotlin's
//   @SerialName carry them, and Engine's coders apply no strategy.
import fs from "node:fs";
import path from "node:path";

const [schemaPath, swiftDir, kotlinDir] = process.argv.slice(2);
const schema = JSON.parse(fs.readFileSync(schemaPath, "utf8"));
const defs = schema.definitions ?? {};

const header = (c) =>
  [
    `${c} Generated by scripts/build/engine-contract-apps.sh from engine/contract/engine.schema.json;`,
    `${c} do not edit. Change the engine's contract and run the script.`,
    "",
  ].join("\n");

const pascal = (s) =>
  s
    .split(/[^A-Za-z0-9]+/)
    .filter(Boolean)
    .map((w) => w[0].toUpperCase() + w.slice(1))
    .join("");
function camel(key) {
  const words = key.split(/[^A-Za-z0-9]+/).filter(Boolean);
  if (words.length === 0) return "value";
  let name =
    words[0] +
    words
      .slice(1)
      .map((w) => w[0].toUpperCase() + w.slice(1))
      .join("");
  if (/^[A-Z]+$/.test(words[0])) name = words[0].toLowerCase() + name.slice(words[0].length);
  else name = name[0].toLowerCase() + name.slice(1);
  return /^[0-9]/.test(name) ? `n${name}` : name;
}

const SWIFT_KEYWORDS = new Set(
  (
    "associatedtype class deinit enum extension fileprivate func import init inout internal let open operator private " +
    "protocol public rethrows static struct subscript typealias var break case continue default defer do else " +
    "fallthrough for guard if in repeat return switch where while as Any catch false is nil super self Self throw " +
    "throws true try Type"
  ).split(" "),
);
const KOTLIN_KEYWORDS = new Set(
  "as break class continue do else false for fun if in interface is null object package return super this throw true try typealias typeof val var when while".split(
    " ",
  ),
);
const swiftId = (n) => (SWIFT_KEYWORDS.has(n) ? `\`${n}\`` : n);
const kotlinId = (n) => (KOTLIN_KEYWORDS.has(n) ? `\`${n}\`` : n);

// ---- The contract read into a small model of types -------------------
//
// A type is one of:
//   {kind: "prim", swift, kotlin}          Double, String, Bool, Int
//   {kind: "any"}                           OpenAPIValueContainer / JsonElement
//   {kind: "list", of}                      [T] / List<T>
//   {kind: "map", of}                       [String: T] / Map<String, T>
//   {kind: "struct", name}                  a struct written once by name
// each with `optional` where null is one of its values.

const structs = new Map(); // name -> {name, description, fields: [{key, name, type, required, description}]}

const PRIMS = {
  number: { swift: "Double", kotlin: "Double" },
  integer: { swift: "Int", kotlin: "Int" },
  string: { swift: "String", kotlin: "String" },
  boolean: { swift: "Bool", kotlin: "Boolean" },
};

function refName(ref) {
  const m = ref.match(/^#\/definitions\/(.+)$/);
  if (!m) throw new Error(`a $ref outside the definitions: ${ref}`);
  return m[1];
}

// The types a schema allows, null apart.
function kinds(s) {
  if (s.type) return { types: [].concat(s.type).filter((t) => t !== "null"), nullable: [].concat(s.type).includes("null") };
  if ("enum" in s) return { types: ["string"], nullable: s.enum.includes(null) };
  if ("const" in s) return { types: ["string"], nullable: s.const === null };
  return { types: [], nullable: false };
}

function typeOf(s, name) {
  if (!s || typeof s !== "object") return { kind: "any" };
  if (s.$ref) return { kind: "struct", name: defStruct(refName(s.$ref)) };
  const union = s.anyOf ?? s.oneOf;
  if (union) {
    const nulls = union.filter((u) => u.type === "null");
    const rest = union.filter((u) => u.type !== "null");
    if (rest.length === 1) return { ...typeOf(rest[0], name), optional: nulls.length > 0 || undefined };
    const tagged = taggedUnion(rest, name);
    if (tagged) return { kind: "struct", name: tagged, optional: nulls.length > 0 || undefined };
    return { kind: "any", optional: nulls.length > 0 || undefined };
  }
  if (s.allOf && s.allOf.length === 1) return typeOf(s.allOf[0], name);
  const { types, nullable } = kinds(s);
  const opt = nullable || undefined;
  if (types.length === 0) return { kind: "any" };
  // A member of two kinds (a number or a string) has no one type.
  if (types.length > 1) {
    if (types.every((t) => t === "number" || t === "integer")) return { kind: "prim", ...PRIMS.number, optional: opt };
    return { kind: "any", optional: opt };
  }
  const t = types[0];
  if (PRIMS[t]) return { kind: "prim", ...PRIMS[t], optional: opt };
  if (t === "array") {
    let items = s.items;
    if (!items && Array.isArray(s.prefixItems)) {
      const shapes = new Set(s.prefixItems.map((p) => JSON.stringify(p)));
      items = shapes.size === 1 ? s.prefixItems[0] : {};
    }
    return { kind: "list", of: typeOf(items ?? {}, `${name}Item`), optional: opt };
  }
  if (t === "object") {
    const props = s.properties ?? {};
    if (Object.keys(props).length === 0) {
      const ap = s.additionalProperties;
      return { kind: "map", of: ap && typeof ap === "object" ? typeOf(ap, `${name}Value`) : { kind: "any" }, optional: opt };
    }
    return { kind: "struct", name: objectStruct(s, name), optional: opt };
  }
  return { kind: "any", optional: opt };
}

function objectStruct(s, name, description) {
  if (structs.has(name)) return name;
  const entry = { name, description: description ?? s.description, fields: [] };
  structs.set(name, entry);
  const required = new Set(s.required ?? []);
  const used = new Set();
  for (const [key, p] of Object.entries(s.properties ?? {})) {
    let field = camel(key);
    while (used.has(field)) field += "_";
    used.add(field);
    const type = typeOf(p, name + pascal(key));
    entry.fields.push({ key, name: field, type, required: required.has(key) && !type.optional, description: p.description });
  }
  return name;
}

// A union of objects told apart by one member each gives as a const (an
// ATC item's "kind": "altitude", "heading"...) is one struct: that member,
// a string, and every shape's other members, each optional, as the shape
// it came in has it. Neither phone has Swift's or Kotlin's sum types from
// a schema, and this reads every shape without a hand-written decoder; a
// member two shapes type differently is OpenAPIValueContainer / JsonElement. None for
// a union that is not so told apart.
function taggedUnion(shapes, name) {
  const objects = shapes.map((u) => (u.$ref ? defs[refName(u.$ref)] : u));
  if (!objects.every((o) => o && o.type === "object" && o.properties)) return null;
  const tag = Object.keys(objects[0].properties).find((k) => objects.every((o) => o.properties[k] && "const" in o.properties[k]));
  if (!tag) return null;
  if (structs.has(name)) return name;
  const entry = {
    name,
    description: shapes.description,
    fields: [
      {
        key: tag,
        name: camel(tag),
        type: { kind: "prim", ...PRIMS.string },
        required: true,
        description: `One of: ${objects.map((o) => o.properties[tag].const).join(", ")}.`,
      },
    ],
  };
  structs.set(name, entry);
  for (const o of objects) {
    for (const [key, p] of Object.entries(o.properties)) {
      if (key === tag) continue;
      const type = typeOf(p, name + pascal(key));
      const known = entry.fields.find((f) => f.key === key);
      if (!known) entry.fields.push({ key, name: camel(key), type, required: false, description: p.description });
      else if (JSON.stringify({ ...known.type, optional: undefined }) !== JSON.stringify({ ...type, optional: undefined }))
        known.type = { kind: "any" };
    }
  }
  return name;
}

function defStruct(def) {
  const s = defs[def];
  if (!s) throw new Error(`no definition ${def}`);
  if (structs.has(def)) return def;
  if ((s.type === "object" || [].concat(s.type).includes("object")) && s.properties) return objectStruct(s, def);
  // A definition that is not an object with members is written where it
  // is used, under its own name.
  const t = typeOf({ ...s, title: undefined }, def);
  // One of several shapes, an object among them, is that object's struct.
  if (t.kind === "struct" && t.name === def) return def;
  aliases.set(def, t);
  return def;
}
const aliases = new Map(); // a definition that is a list, a string... -> its type

const rules = [];
for (const [rule, entry] of Object.entries(schema.properties)) {
  const P = pascal(rule);
  const input = entry.properties.input;
  const answer = entry.properties.answer;
  // The input's members, spread into the function's parameters.
  let inputStruct = null;
  if (input.$ref) inputStruct = defStruct(refName(input.$ref));
  else inputStruct = objectStruct({ ...input, properties: input.properties ?? {} }, `${P}Input`, input.description);
  const answerType = typeOf(answer, `${P}Answer`);
  rules.push({ rule, P, description: entry.description, inputStruct, answerType });
}

// ---- Swift -------------------------------------------------------------

function swiftType(t) {
  let base;
  switch (t.kind) {
    case "prim":
      base = t.swift;
      break;
    case "any":
      base = "OpenAPIValueContainer";
      break;
    case "list":
      base = `[${swiftType(t.of)}]`;
      break;
    case "map":
      base = `[String: ${swiftType(t.of)}]`;
      break;
    case "struct":
      base = aliases.has(t.name) ? swiftType(aliases.get(t.name)) : `EngineContract.${t.name}`;
      break;
  }
  return t.optional ? `${base}?` : base;
}
// A type as a member's or a parameter's: optional where not required.
const swiftField = (f) => (f.required ? swiftType(f.type) : swiftType({ ...f.type, optional: true }));

function swiftDoc(text, indent) {
  if (!text) return "";
  return (
    text
      .trim()
      .split("\n")
      .map((l) => `${indent}/// ${l}`.trimEnd())
      .join("\n") + "\n"
  );
}

function writeSwift() {
  const out = [header("//"), "import Foundation", "import OpenAPIRuntime", ""];
  out.push(
    "/// The engine's inputs and answers by rule, as engine/contract/engine.schema.json",
    "/// types them; Engine's functions in EngineCalls.swift take and return them.",
    "enum EngineContract {",
  );
  for (const s of [...structs.values()].sort((a, b) => a.name.localeCompare(b.name))) {
    out.push("");
    out.push(swiftDoc(s.description, "    ").trimEnd());
    out.push(`    struct ${s.name}: Codable, Equatable, Sendable {`);
    for (const f of s.fields) {
      if (f.description) out.push(swiftDoc(f.description, "        ").trimEnd());
      out.push(`        var ${swiftId(f.name)}: ${swiftField(f)}`);
    }
    if (s.fields.some((f) => f.name !== f.key)) {
      out.push("");
      out.push("        enum CodingKeys: String, CodingKey {");
      for (const f of s.fields)
        out.push(
          f.name === f.key ? `            case ${swiftId(f.name)}` : `            case ${swiftId(f.name)} = ${JSON.stringify(f.key)}`,
        );
      out.push("        }");
    }
    out.push("    }");
  }
  out.push("}", "");
  fs.writeFileSync(path.join(swiftDir, "EngineContract.swift"), out.filter((l, i, a) => !(l === "" && a[i - 1] === "")).join("\n"));

  const calls = [header("//"), "import Foundation", "import OpenAPIRuntime", ""];
  calls.push(
    "/// Every rule of the engine by name, typed: its input's members as",
    "/// parameters and its answer as the contract's type. Each throws",
    "/// Engine.Refused (or the decoder's error) where the engine refused the",
    "/// input or answered in a shape the contract does not give, and logs it.",
    "extension Engine {",
  );
  for (const r of rules) {
    const s = structs.get(r.inputStruct);
    const params = s.fields.map((f) => `${swiftId(f.name)}: ${swiftField(f)}${f.required ? "" : " = nil"}`);
    // An argument's label may be a keyword as it is; its value, a parameter, is escaped.
    const args = s.fields.map((f) => `${["inout", "var", "let"].includes(f.name) ? swiftId(f.name) : f.name}: ${swiftId(f.name)}`);
    calls.push("");
    calls.push(swiftDoc(r.description, "    ").trimEnd());
    calls.push(`    static func ${swiftId(camel(r.rule))}(${params.join(", ")}) throws -> ${swiftType(r.answerType)} {`);
    // Self.rule: a rule whose input has a field named `rule` (tfr_read) would
    // otherwise hide the helper behind its own parameter.
    calls.push(`        try Self.rule(${JSON.stringify(r.rule)}, EngineContract.${r.inputStruct}(${args.join(", ")}))`);
    calls.push("    }");
  }
  calls.push("}", "");
  fs.writeFileSync(path.join(swiftDir, "EngineCalls.swift"), calls.filter((l, i, a) => !(l === "" && a[i - 1] === "")).join("\n"));
}

// ---- Kotlin ------------------------------------------------------------

function kotlinType(t) {
  let base;
  switch (t.kind) {
    case "prim":
      base = t.kotlin;
      break;
    case "any":
      base = "JsonElement";
      break;
    case "list":
      base = `List<${kotlinType(t.of)}>`;
      break;
    case "map":
      base = `Map<String, ${kotlinType(t.of)}>`;
      break;
    case "struct":
      base = aliases.has(t.name) ? kotlinType(aliases.get(t.name)) : `EngineContract.${t.name}`;
      break;
  }
  // An alias that is itself nullable (EndHeadings) is not made nullable
  // twice: Kotlin warns of the redundant "?", and the app's build fails
  // on a warning.
  return t.optional && !base.endsWith("?") ? `${base}?` : base;
}
const kotlinField = (f) => (f.required ? kotlinType(f.type) : kotlinType({ ...f.type, optional: true }));

function kdoc(text, indent) {
  if (!text) return "";
  // Kotlin's block comments nest: a "/*" inside one opens a comment the
  // closing "*/" never ends.
  const lines = text.trim().replaceAll("*/", "*&#47;").replaceAll("/*", "/&#42;").split("\n");
  return [`${indent}/**`, ...lines.map((l) => `${indent} * ${l}`.trimEnd()), `${indent} */`].join("\n") + "\n";
}

function writeKotlin() {
  const pkg = "app.wingtipmaps.android.engine.generated";
  const out = [
    header("//"),
    `package ${pkg}`,
    "",
    "import kotlinx.serialization.SerialName",
    "import kotlinx.serialization.Serializable",
    "import kotlinx.serialization.json.JsonElement",
    "",
  ];
  out.push("/** The engine's inputs and answers by rule, as engine/contract/engine.schema.json types them. */");
  out.push("object EngineContract {");
  for (const s of [...structs.values()].sort((a, b) => a.name.localeCompare(b.name))) {
    out.push("");
    if (s.description) out.push(kdoc(s.description, "    ").trimEnd());
    out.push("    @Serializable");
    if (s.fields.length === 0) {
      out.push(`    class ${s.name} {`);
      out.push("        override fun equals(other: Any?): Boolean = other is " + s.name);
      out.push("        override fun hashCode(): Int = 0");
      out.push("    }");
      continue;
    }
    out.push(`    data class ${s.name}(`);
    for (const f of s.fields) {
      if (f.description) out.push(kdoc(f.description, "        ").trimEnd());
      if (f.name !== f.key) out.push(`        @SerialName(${JSON.stringify(f.key)})`);
      out.push(`        val ${kotlinId(f.name)}: ${kotlinField(f)}${f.required ? "" : " = null"},`);
    }
    out.push("    )");
  }
  out.push("}", "");
  fs.writeFileSync(path.join(kotlinDir, "EngineContract.kt"), out.join("\n"));

  const calls = [
    header("//"),
    `package ${pkg}`,
    "",
    "import app.wingtipmaps.android.engine.Engine",
    "import kotlinx.serialization.json.JsonElement",
    "",
  ];
  calls.push(
    "// Every rule of the engine by name, typed: its input's members as",
    "// parameters and its answer as the contract's type, in a Result that",
    "// holds EngineException (or the decoder's error) where the engine refused",
    "// the input or answered in a shape the contract does not give. Engine.rule",
    "// logs each failure.",
  );
  for (const r of rules) {
    const s = structs.get(r.inputStruct);
    const params = s.fields.map((f) => `${kotlinId(f.name)}: ${kotlinField(f)}${f.required ? "" : " = null"}`);
    const args = s.fields.map((f) => `${kotlinId(f.name)} = ${kotlinId(f.name)}`);
    const ctor = s.fields.length === 0 ? `EngineContract.${r.inputStruct}()` : `EngineContract.${r.inputStruct}(${args.join(", ")})`;
    calls.push("");
    if (r.description) calls.push(kdoc(r.description, "").trimEnd());
    calls.push(`fun Engine.${kotlinId(camel(r.rule))}(${params.join(", ")}): Result<${kotlinType(r.answerType)}> =`);
    calls.push(`    rule(${JSON.stringify(r.rule)}, ${ctor})`);
  }
  calls.push("");
  fs.writeFileSync(path.join(kotlinDir, "EngineCalls.kt"), calls.join("\n"));
}

fs.mkdirSync(swiftDir, { recursive: true });
fs.mkdirSync(kotlinDir, { recursive: true });
writeSwift();
writeKotlin();
console.log(`${rules.length} rules, ${structs.size} types`);
