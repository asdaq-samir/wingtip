"""services/planner/app/generated/planner_calls.py, from the planner's OpenAPI
document (services/planner/openapi.json): the planner's own HTTP API as
async functions for its MCP connector's tools (app.mcp), one per operation
answering JSON, its path, query, header and body parameters typed from the
document. Each asks the planner's ASGI app in-process through
app.mcp.calls.planner, which says a refusal as the tool's error. A route
renamed or gone fails where a tool imports it, not on a pilot's call (the
owner's rule of 2026-11-09: what can be generated is never hand-written).

    python3 scripts/build/planner_calls.py           # write it
    python3 scripts/build/planner_calls.py --check   # fail if it differs

The standard library alone, so it runs anywhere a Python does;
scripts/build/planner-calls.sh is the same, and the planner's suite runs
--check (scripts/ci/python_suite.sh).
"""

from __future__ import annotations

import argparse
import difflib
import json
import keyword
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
PLANNER_SPEC = ROOT / "services/planner/openapi.json"
OUT = ROOT / "services/planner/app/generated"

HEADER = (
    "# GENERATED by scripts/build/planner_calls.py from {source}.\n"
    "# Do not edit: change the source and run scripts/build/planner-calls.sh.\n"
    "# ruff: noqa: E501\n"
)

HEAD = '''"""The planner's own HTTP API as async functions, for its MCP connector's
tools (app.mcp): one per operation answering JSON, its parameters typed from
services/planner/openapi.json, each asked of the planner's ASGI app
in-process (app.mcp.calls.planner), which says a refusal as the tool's
error. The answers are the planner's JSON as its response models shaped it.
A tool imports the functions it calls by name, so a route renamed or gone
fails where the tool is imported, not on a pilot's call."""
from __future__ import annotations

from typing import Any, Literal  # noqa: F401 -- Literal is used where an operation has an enum
from urllib.parse import quote

from ..mcp.calls import planner as _send


def _seg(value: Any) -> str:
    """A path parameter as one segment, so a stray slash cannot reach
    another path."""
    return quote(str(value), safe="")
'''


def _json_type(schema: dict) -> str:
    """A JSON schema as a Python annotation over plain JSON: the tools read
    the planner's answers as dicts, and send dicts."""
    if not schema or "$ref" in schema:
        return "dict[str, Any]" if schema else "Any"
    for key in ("anyOf", "oneOf"):
        if key in schema:
            parts = list(dict.fromkeys(_json_type(s) for s in schema[key]))
            return "Any" if "Any" in parts else " | ".join(parts)
    if "enum" in schema:
        return "Literal[" + ", ".join(repr(v) for v in schema["enum"]) + "]"
    if "const" in schema:
        return f"Literal[{schema['const']!r}]"
    kind = schema.get("type")
    if isinstance(kind, list):
        return " | ".join(dict.fromkeys(_json_type({**schema, "type": k}) for k in kind))
    if kind == "array":
        return f"list[{_json_type(schema.get('items') or {})}]"
    if kind == "object":
        extra = schema.get("additionalProperties")
        return f"dict[str, {_json_type(extra) if isinstance(extra, dict) else 'Any'}]"
    return {"string": "str", "number": "float", "integer": "int", "boolean": "bool", "null": "None"}.get(kind, "Any")


def _ident(name: str) -> str:
    out = re.sub(r"\W", "_", name).lower()
    return out + "_" if keyword.iskeyword(out) else out


def _function_name(op_id: str, path: str, method: str, taken: set[str]) -> str:
    """FastAPI's operationId is the route function's name, the path and the
    method run together; the function's name alone, where it is unique."""
    suffix = re.sub(r"\W", "_", path) + "_" + method
    name = op_id[: -len(suffix)] if op_id.endswith(suffix) else op_id
    return op_id if name in taken or not name.isidentifier() else name


def _operations(spec: dict):
    for path, ops in sorted(spec["paths"].items()):
        for method, op in sorted(ops.items()):
            if method not in ("get", "post", "put", "delete"):
                continue
            ok = op.get("responses", {}).get("200", {}).get("content", {})
            if "application/json" not in ok:
                continue  # a tile, a file, a stream: not an answer to read
            yield path, method, op


def planner_calls(spec: dict) -> str:
    lines: list[str] = []
    taken: set[str] = set()
    for path, method, op in _operations(spec):
        fn = _function_name(op["operationId"], path, method, taken)
        taken.add(fn)
        args, query, headers, path_args = [], [], [], {}
        for p in sorted(op.get("parameters", []), key=lambda p: not p.get("required")):
            arg = _ident(p["name"])
            annotation = _json_type(p.get("schema") or {})
            if p.get("required"):
                args.append(f"{arg}: {annotation}")
            else:
                args.append(f"{arg}: {annotation} = None" if "None" in annotation.split(" | ") else f"{arg}: {annotation} | None = None")
            target = {"query": query, "header": headers}.get(p["in"])
            if target is not None:
                target.append(f"{p['name']!r}: {arg}")
            elif p["in"] == "path":
                path_args[p["name"]] = arg
        body = op.get("requestBody", {}).get("content", {}).get("application/json", {}).get("schema")
        if body is not None:
            args.insert(0, "body: dict[str, Any]" if op["requestBody"].get("required", False) else "body: dict[str, Any] | None = None")
        url = re.sub(r"\{([^}]+)\}", lambda m: "{_seg(" + path_args[m.group(1)] + ")}", path)
        url = f'f"{url}"' if path_args else repr(url)
        doc = (op.get("summary") or op["operationId"]).strip()
        lines += [
            "",
            "",
            f"async def {fn}({'*, ' if args else ''}{', '.join(args)}) -> Any:",
            f'    """{method.upper()} {path}: {doc}"""',
            f"    return await _send({method.upper()!r}, {url}, query={{{', '.join(query)}}}, "
            f"body={'body' if body is not None else 'None'}, headers={{{', '.join(headers)}}})",
        ]
    return HEADER.format(source="services/planner/openapi.json") + HEAD + "\n".join(lines) + "\n"


def generate() -> dict[Path, str]:
    spec = json.loads(PLANNER_SPEC.read_text())
    return {
        OUT / "__init__.py": '"""Generated code: see scripts/build/planner_calls.py. Do not edit."""\n',
        OUT / "planner_calls.py": planner_calls(spec),
    }


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    parser.add_argument("--check", action="store_true", help="fail where a committed file differs from what is generated")
    check = parser.parse_args().check
    stale = []
    for path, text in generate().items():
        have = path.read_text() if path.exists() else ""
        if have == text:
            continue
        rel = str(path.relative_to(ROOT))
        if check:
            stale.append(rel)
            sys.stdout.writelines(list(difflib.unified_diff(have.splitlines(True), text.splitlines(True), rel, rel + " (generated)"))[:40])
        else:
            path.write_text(text)
            print(f"wrote {rel}")
    if stale:
        print("\nOut of date; run scripts/build/planner-calls.sh:\n  " + "\n  ".join(stale))
        return 1
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
