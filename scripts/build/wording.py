#!/usr/bin/env python3
"""Generate each app's shared words, and their table, from design/wording.json.

The words a pilot meets on all three apps (the names of the controls and
figures, the shared progress, error and empty-state lines) are written
once and generated into each platform in its own idiom, as the tokens and
the screens are: a TypeScript object for the web, a Swift enum of
String(localized:) for iOS (so the string catalog keeps each), an Android
string resource each, and the table in docs/design/rules.md, section 18.

Each word's kind is checked here, so a word that breaks the app's rules
for words (rules.md section 18, decision 0021) fails the generation:

- a label is in Title Case, Apple's title style: every word capitalised but
  the articles, the conjunctions and the short prepositions, unless one
  begins or ends it; the FAA's codes keep their capitals;
- a sentence begins with a capital and ends with a full stop or a question
  mark; progress ends with one ellipsis character; a value (what a figure
  reads) has no closing stop;
- no word holds "..." (the ellipsis is one character), "aeroplane", or
  "aircraft" or "plane" where the app says "airplane" (CLAUDE.md,
  "Writing"), unless its "faa" says why the FAA's own term is kept.

Standard library only; run it through scripts/build/wording.sh, which CI
runs with --check.

Usage: wording.py [--check]
"""

import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
SOURCE = ROOT / "design" / "wording.json"
WEB_TS = ROOT / "apps/web/src/lib/wording/generated/wording.ts"
IOS_SWIFT = ROOT / "apps/ios/Wingtip/Design/Generated/Wording.swift"
ANDROID_XML = ROOT / "apps/android/app/src/main/res/values/wording_strings.xml"
DOC = ROOT / "docs" / "design" / "rules.md"
DOC_BEGIN = "<!-- BEGIN generated from design/wording.json by scripts/build/wording.sh -->"
DOC_END = "<!-- END generated wording -->"

BANNER = "Generated by scripts/build/wording.sh from design/wording.json -- do not edit; change the words and run it again."
XML_BANNER = BANNER.replace(" -- ", "; ")
KINDS = ("label", "sentence", "progress", "value")
# Apple's title style leaves these lower case inside a label: the
# articles, the coordinating conjunctions and the prepositions of four
# letters or fewer.
MINOR = set("a an the and but or nor for so yet as at by in into of off on onto out per to up via with from".split())
NOT_OURS = re.compile(r"\b(aeroplanes?|aircraft|planes?)\b", re.IGNORECASE)


def label_problem(text):
    """Why a label is not in Title Case, or None."""
    words = re.findall(r"[A-Za-z][A-Za-z'’]*", text)
    for i, word in enumerate(words):
        edge = i == 0 or i == len(words) - 1
        if word.lower() in MINOR and not edge:
            if word != word.lower():
                return f"{word!r} is a short word, lower case inside a label"
        elif not word[0].isupper():
            return f"{word!r} begins with a capital in a label"
    return None


def problems(key, word):
    text, kind = word["text"], word["kind"]
    found = []
    if kind not in KINDS:
        found.append(f"kind is one of {', '.join(KINDS)}")
    if "..." in text:
        found.append('"..." is one ellipsis character, "…"')
    if NOT_OURS.search(text) and "faa" not in word:
        found.append('says "airplane", or "faa" says whose term it keeps')
    if kind == "label":
        why = label_problem(text)
        if why:
            found.append(why)
    elif not (text[0].isupper() or text[0].isdigit()):
        found.append("begins with a capital")
    if kind == "sentence" and not text.endswith((".", "?")):
        found.append("a sentence ends with a full stop or a question mark")
    if kind == "progress" and not (text.endswith("…") and not text.endswith("……")):
        found.append("progress ends with one ellipsis character")
    if kind == "value" and text.endswith("."):
        found.append("a value has no closing stop")
    return [f"design/wording.json: {key}: {p}" for p in found]


def load():
    spec = json.loads(SOURCE.read_text())
    errors = []
    for key, word in spec["words"].items():
        if not re.fullmatch(r"[a-z][a-z0-9]*(_[a-z0-9]+)*", key):
            errors.append(f"design/wording.json: {key!r} is not snake_case")
        errors += problems(key, word)
    if errors:
        raise SystemExit("\n".join(errors))
    return spec["words"]


def camel(key):
    head, *rest = key.split("_")
    return head + "".join(part.capitalize() for part in rest)


def quoted(text):
    return json.dumps(text, ensure_ascii=False)


def web(words):
    rows = "\n".join(f"  /** {w['about']} */\n  {camel(k)}: {quoted(w['text'])}," for k, w in words.items())
    return f"""// {BANNER}

/** The words every app says the same (design/wording.json; docs/design/rules.md, section 18). */
export const WORDING = {{
{rows}
}} as const;

"""


def ios(words):
    rows = "\n".join(
        f"    /// {w['about']}\n    static let {camel(k)} = String(localized: {quoted(w['text'])})" for k, w in words.items()
    )
    return f"""// {BANNER}

import Foundation

/// The words every app says the same (design/wording.json;
/// docs/design/rules.md, section 18), each kept by the string catalog.
enum Wording {{
{rows}
}}
"""


def xml_text(text):
    text = text.replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;")
    text = text.replace("\\", "\\\\").replace("'", "\\'").replace('"', '\\"')
    # Android reads a leading @ or ? as a reference.
    return "\\" + text if text.startswith(("@", "?")) else text


def android(words):
    rows = "\n".join(
        f"    <!-- {w['about'].replace('--', '-')} -->\n    <string name=\"wording_{k}\">{xml_text(w['text'])}</string>"
        for k, w in words.items()
    )
    return f"""<?xml version="1.0" encoding="utf-8"?>
<!-- {XML_BANNER} -->
<!-- Every word is here for every app; one Android does not say yet is no lint failure. -->
<resources xmlns:tools="http://schemas.android.com/tools" tools:ignore="UnusedResources">
{rows}
</resources>
"""


def doc_table(words):
    rows = [f"| `{k}` | {w['kind']} | {w['text'].replace('|', '·')} | {w['about']} |" for k, w in words.items()]
    head = [
        DOC_BEGIN,
        "",
        "| Key | Kind | Words | Where |",
        "|---|---|---|---|",
    ]
    return "\n".join(head + rows + ["", DOC_END])


def doc(words, current):
    if DOC_BEGIN not in current or DOC_END not in current:
        raise SystemExit(f"{DOC.relative_to(ROOT)}: no {DOC_BEGIN!r} ... {DOC_END!r} block to fill")
    before, rest = current.split(DOC_BEGIN, 1)
    _, after = rest.split(DOC_END, 1)
    return before + doc_table(words) + after


def main():
    check = "--check" in sys.argv[1:]
    words = load()
    outputs = {WEB_TS: web(words), IOS_SWIFT: ios(words), ANDROID_XML: android(words)}
    outputs[DOC] = doc(words, DOC.read_text())
    stale = []
    for path, text in outputs.items():
        if (path.read_text() if path.exists() else None) == text:
            continue
        if check:
            stale.append(str(path.relative_to(ROOT)))
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(text)
            print(f"wrote {path.relative_to(ROOT)}")
    if stale:
        print("Out of date with design/wording.json (run scripts/build/wording.sh and commit):", *stale, sep="\n  ")
        sys.exit(1)


if __name__ == "__main__":
    main()
