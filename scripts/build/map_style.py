"""The map's overlay layers for each app, from design/map-style.json.

design/map-style.json is the one source of the overlay layers the web's
and Android's MapLibre maps draw from the cycle's vector tiles: each
layer's id, source, filter, layout, paint, zooms and order. This writes

  apps/web/src/lib/generated/overlayLayers.ts                the web's
  apps/android/.../map/generated/OverlayStyle.kt             Android's (map_style_android.py)

with design/tokens.json's values in place and the file's vocabulary
resolved (its "$description" says what each word does). What each app
does for itself -- the words' font and size with Larger Map Labels, their
ink and halo after dark -- is left to the app: the web's as calls of its
lib/map/gl/layers/common (labelText, labelHalo, labelInk), Android's as
plain values its MapLabels turns for the night. iOS draws with MapKit and
reads none of it.

Standard library only; run it through scripts/build/map-style.sh, which
CI runs with --check.
"""

import json
import re
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from design_tokens_colour import hex6, rgba  # noqa: E402

ROOT = Path(__file__).resolve().parents[2]
SOURCE = ROOT / "design/map-style.json"
TOKENS = ROOT / "design/tokens.json"
WEB_TS = ROOT / "apps/web/src/lib/generated/overlayLayers.ts"
ANDROID_KT = ROOT / "apps/android/app/src/main/kotlin/app/wingtipmaps/android/map/generated/OverlayStyle.kt"
BANNER = "Generated by scripts/build/map-style.sh from design/map-style.json -- do not edit; change the style and run it again."
REF = re.compile(r"^\{([a-z0-9.-]+)\}$")


class Hook:
    """A part each app writes itself: `kind` is label, halo, ink or haloColour."""

    def __init__(self, kind, value):
        self.kind, self.value = kind, value


def camel(name):
    head, *rest = name.split("-")
    return head + "".join(p[:1].upper() + p[1:] for p in rest)


def upper(name):
    return re.sub(r"(?<!^)(?=[A-Z])", "_", name).upper()


class Resolver:
    def __init__(self, style, tokens, app):
        self.style, self.tokens, self.app = style, tokens, style["apps"][app]
        self.states, self.features = set(), set()

    def token(self, path):
        node = self.tokens
        for part in path.split("."):
            node = node[part]
        value = node["$value"] if isinstance(node, dict) and "$value" in node else node
        if isinstance(value, str) and REF.match(value):
            return self.token(REF.match(value).group(1))
        if isinstance(value, str):
            return hex6(rgba(value))
        return value

    def named(self, table, use):
        entry = self.style[table].get(use["$use"])
        if entry is None:
            raise SystemExit(f"design/map-style.json: no {table} entry {use['$use']!r}")
        args = {k: v for k, v in use.items() if k != "$use"}
        return self.walk(entry["$value"], {k: self.walk(v, {}) for k, v in args.items()})

    def zoom(self, z, args):
        return self.walk(z, args) - 1

    def walk(self, node, args):
        if isinstance(node, str):
            m = REF.match(node)
            return self.token(m.group(1)) if m else node
        if isinstance(node, list):
            out = [self.walk(n, args) for n in node]
            if len(out) == 2 and out[0] == "global-state" and isinstance(out[1], str):
                self.states.add(out[1])
            if len(out) == 2 and out[0] == "feature-state" and isinstance(out[1], str):
                self.features.add(out[1])
            return out
        if not isinstance(node, dict):
            return node
        if "$arg" in node:
            return args[node["$arg"]]
        if "$use" in node and "$value" not in node:
            table = "expressions" if node["$use"] in self.style["expressions"] else "fragments"
            return self.named(table, node)
        if "$zoom" in node:
            return self.zoom(node["$zoom"], args)
        if "$byZoom" in node:
            stops = [x for z, v in node["$byZoom"] for x in (self.zoom(z, args), self.walk(v, args))]
            return ["interpolate", ["linear"], ["zoom"], *stops]
        if "$markScale" in node:
            return node["$markScale"] * self.app["markScale"]
        if "$ink" in node:
            return Hook("ink", self.walk(node["$ink"], args))
        if "$haloColour" in node:
            return Hook("haloColour", node["$haloColour"])
        out = {}
        withs = node.get("$with", [])
        for w in withs if isinstance(withs, list) else [withs]:
            merge(out, self.named("fragments", w if isinstance(w, dict) else {"$use": w}))
        for k, v in node.items():
            if k in ("$comment", "$with"):
                continue
            if k in ("$label", "$halo"):
                out[(k[1:], v)] = None
                continue
            merge(out, {k: self.walk(v, args)})
        return out


def merge(into, more):
    """`more` over `into`, objects merged key by key (a fragment's layout with a layer's own)."""
    for k, v in more.items():
        if isinstance(v, dict) and isinstance(into.get(k), dict):
            merge(into[k], v)
        else:
            into[k] = v


def layers(r, part):
    """Each layer of `part` resolved, and its switch's group taken off."""
    out, groups = [], {}
    for spec in r.style[part]:
        layer = r.walk(spec, {})
        group = layer.pop("group", None)
        if group:
            groups.setdefault(group, []).append(layer["id"])
        if layer.get("source") not in [v for k, v in r.style["sources"].items() if not k.startswith("$")]:
            raise SystemExit(f"design/map-style.json: {layer['id']} draws from no declared source")
        out.append(layer)
    return out, groups


def sources(style):
    return "{ " + ", ".join(f"{k}: {json.dumps(v)}" for k, v in style["sources"].items() if not k.startswith("$")) + " }"


def public(table):
    return [k for k, v in table.items() if not k.startswith("$") and "$arg" not in json.dumps(v)]


# ---- The web: TypeScript, its hooks calls of lib/map/gl/layers/common ----


def ts(node, indent=""):
    inner = indent + "  "
    if isinstance(node, Hook):
        if node.kind == "ink":
            return f"labelInk({ts(node.value, indent)})"
        return f'labelHalo("{camel(node.value)}")["text-halo-color"]!'
    if isinstance(node, list):
        return "[" + ", ".join(ts(n, indent) for n in node) + "]"
    if isinstance(node, dict) and not node:
        return "{}"
    if isinstance(node, dict):
        parts = []
        for k, v in node.items():
            if isinstance(k, tuple):
                call = "labelText" if k[0] == "label" else "labelHalo"
                parts.append(f'...{call}("{camel(k[1])}")')
            else:
                parts.append(f"{json.dumps(k)}: {ts(v, inner)}")
        return "{\n" + "".join(f"{inner}{p},\n" for p in parts) + indent + "}"
    return json.dumps(node)


LAYOUT = 'NonNullable<SymbolLayerSpecification["layout"]>'


def keys(table):
    return " | ".join(json.dumps(k) for k in table)


def web(style, tokens):
    r = Resolver(style, tokens, "web")
    lines, g1 = layers(r, "lines")
    marks, g2 = layers(r, "marks")
    groups = {**g1, **{k: g1.get(k, []) + v for k, v in g2.items()}}
    exprs = {camel(k): r.named("expressions", {"$use": k}) for k in public(style["expressions"])}
    frags = {camel(k): r.named("fragments", {"$use": k}) for k in public(style["fragments"])}
    names = lambda s: "{ " + ", ".join(f"{camel(n)}: {json.dumps(n)}" for n in sorted(s)) + " }"  # noqa: E731
    return "\n".join(
        [
            f"/* {BANNER} */",
            'import type { ExpressionSpecification, LayerSpecification, SymbolLayerSpecification } from "maplibre-gl";',
            'import { labelHalo, labelInk, labelText } from "../map/gl/layers/common";',
            "",
            "/** The overlay layers under the route's slot, bottom to top (glLayer's SLOTS `lines`). */",
            f"export const OVERLAY_LINES: LayerSpecification[] = {ts(lines)} as never;",
            "/** And over it: the navaids, the fixes and waypoints, the airports. */",
            f"export const OVERLAY_MARKS: LayerSpecification[] = {ts(marks)} as never;",
            "/** The layers each switch turns off, by the switch. */",
            f"export const OVERLAY_GROUPS = {json.dumps(groups)} as const;",
            "/** The sources the layers draw from, by name: each app's own to add. */",
            f"export const OVERLAY_SOURCES = {sources(style)} as const;",
            "/** The map's global state the layers read (MapLibre's `global-state`), set by the app. */",
            f"export const OVERLAY_STATE = {names(r.states)} as const;",
            "/** The feature states they read. */",
            f"export const OVERLAY_FEATURE_STATE = {names(r.features)} as const;",
            "/** The layers' named expressions, for the app's own layers over the same tiles. */",
            f"export const OVERLAY_EXPRESSIONS: Record<{keys(exprs)}, ExpressionSpecification> = {ts(exprs)} as never;",
            "/** The layers' named parts of a layout. */",
            f"export const OVERLAY_FRAGMENTS: Record<{keys(frags)}, {LAYOUT}> = {ts(frags)} as never;",
            "",
        ]
    )


def main():
    check = "--check" in sys.argv[1:]
    style, tokens = json.loads(SOURCE.read_text()), json.loads(TOKENS.read_text())
    from map_style_android import android  # noqa: E402 -- it builds on this module's Resolver

    outputs = {WEB_TS: web(style, tokens), ANDROID_KT: android(style, tokens)}
    stale = []
    for path, text in outputs.items():
        if (path.read_text() if path.exists() else None) == text:
            continue
        if check:
            stale.append(str(path.relative_to(ROOT)))
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(text)
            print(f"wrote {path.relative_to(ROOT)}")
    if stale:
        print("Out of date with design/map-style.json (run scripts/build/map-style.sh and commit):", *stale, sep="\n  ")
        sys.exit(1)


if __name__ == "__main__":
    main()
