#!/usr/bin/env python3
"""No source file grows past 400 lines, and no new one past 300 (the
modular-architecture rule; the owner's 300-line target, 2026-11-09).

A file that does one thing is short; the god files (a 2,250-line hook, a
3,100-line schemas module) made every change touch many places. This holds
the budget without a big-bang split: every tracked source file -- TypeScript,
Python, Rust, Swift, Kotlin, Java -- is at most BUDGET lines, except those in
scripts/ci/file_sizes_allow.txt, each listed at the lines it had when it was
listed, which it may not pass. A new file over the budget, or a listed one
that grew, fails: split it (or take what grew out). A listed file that
shrank is said, and `--write` lowers its count (and drops it once it is
within the budget), so the list only shrinks. With `--base REF` (CI passes
main's), an entry added to the list or raised against REF's list fails too:
the list is not a way round the budget. With `--base`, a file that is new
against REF is held to NEW_BUDGET (300 lines), the owner's target; the
older ones keep the 400 and their allowances. Files given on the command
line (the edit-time hook passes one) are the only ones checked.

Shell, the build's JavaScript (.mjs, .js), C#, and Gradle's Kotlin and
Groovy scripts are counted too since 2026-11-12 (check.sh had grown to 410
lines unseen; the simplicity audit's finding 7). A file of those already
over the budget then was listed at its size; an entry added against REF is
refused unless it is one of those kinds and was there at REF.

Generated files are left out (their generators are checked elsewhere):
anything under a generated/ or Generated/ folder, the web's types from the
API documents and the engine's contract, and *.d.ts.

The standard library only, for the Mac's python3 (3.9) and CI's.

  python3 scripts/ci/file_sizes.py                  check
  python3 scripts/ci/file_sizes.py --base origin/main
  python3 scripts/ci/file_sizes.py --write          rewrite the list's counts down
"""

import re
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
ALLOW = ROOT / "scripts/ci/file_sizes_allow.txt"
# The wave's files of 301-400 lines that were new against main when the
# 300-line budget for new files came in (2026-11-12), each at its size then:
# held there, and gone from the list once the file is within 300.
NEW_ALLOW = ROOT / "scripts/ci/file_sizes_new_allow.txt"
BUDGET = 400
NEW_BUDGET = 300
# The kinds of file first counted on 2026-11-12: one of these there at REF
# may join the list once, at its size then, as the budget reaches it.
COUNTED_SINCE_2026_11_12 = (".sh", ".mjs", ".js", ".cjs", ".cs", ".kts", ".gradle")
SUFFIXES = (".ts", ".tsx", ".py", ".rs", ".swift", ".kt", ".java", ".sh", ".mjs", ".js", ".cjs", ".cs", ".kts", ".gradle")
# apps/ios/WingtipAPI is generated by scripts/build/api-models-apps.sh from the
# OpenAPI documents; `api-models-apps.sh --check` verifies it.
GENERATED = re.compile(
    r"(^|/)(generated|Generated)/|\.d\.ts$|^apps/web/src/lib/engine/contract\.ts$|(^|/)gradlew$|/lib/engine/pkg/|^apps/ios/WingtipAPI/"
)
HEADER = """\
# Source files over scripts/ci/file_sizes.py's budget (400 lines) when the
# budget came in, each at the lines it had then: "<path> <lines>". A file
# here may not grow past its count, and none is added; split one and lower
# its count (`python3 scripts/ci/file_sizes.py --write`), and it leaves the
# list once it is within the budget. The counts raised on 2026-11-09, and
# the files first listed then, are the formatters' growth (the whole-tree
# reformat of scripts/dev/format.sh, a commit a language), not new code.
"""


def tracked() -> list:
    out = subprocess.run(["git", "-C", str(ROOT), "ls-files", "-z"], capture_output=True, check=True).stdout
    return [p for p in out.decode().split("\0") if p.endswith(SUFFIXES) and not GENERATED.search(p)]


def lines_of(path: str) -> int:
    try:
        with open(ROOT / path, "rb") as f:
            return sum(1 for _ in f)
    except FileNotFoundError:
        return 0


def read_allow(text: str) -> dict:
    allowed = {}
    for raw in text.splitlines():
        line = raw.strip()
        if line and not line.startswith("#"):
            path, count = line.rsplit(None, 1)
            allowed[path] = int(count)
    return allowed


def write_allow(allowed: dict) -> None:
    body = "".join(f"{p} {n}\n" for p, n in sorted(allowed.items()))
    ALLOW.write_text(HEADER + "\n" + body)


def at(ref: str, path: str) -> "int | None":
    """The file's lines at REF, or None where it is not there (a new file)."""
    shown = subprocess.run(["git", "-C", str(ROOT), "show", f"{ref}:{path}"], capture_output=True)
    return shown.stdout.count(b"\n") if shown.returncode == 0 else None


def main(argv: list) -> int:
    allowed = read_allow(ALLOW.read_text()) if ALLOW.exists() else {}
    ref = argv[argv.index("--base") + 1] if "--base" in argv else None
    given = [a for a in argv if not a.startswith("--") and a != ref]
    if given:
        paths = [Path(a).resolve().relative_to(ROOT).as_posix() if Path(a).is_absolute() else a for a in given]
        paths = [p for p in paths if p.endswith(SUFFIXES) and not GENERATED.search(p)]
        allowed = {p: n for p, n in allowed.items() if p in paths}
    else:
        paths = tracked()
    sizes = {p: lines_of(p) for p in paths}
    over = {p: n for p, n in sizes.items() if n > BUDGET}

    new_allowed = read_allow(NEW_ALLOW.read_text()) if NEW_ALLOW.exists() else {}
    if "--write" in argv:
        if given:
            print("--write reads every file: run it without file names")
            return 2
        kept = {p: min(n, allowed[p]) if p in allowed else n for p, n in over.items() if p in allowed or "--seed" in argv}
        write_allow(kept)
        held = {p: min(sizes.get(p, 0), n) for p, n in new_allowed.items() if NEW_BUDGET < sizes.get(p, 0) <= BUDGET}
        NEW_ALLOW.write_text(NEW_ALLOW.read_text().split("\n\n", 1)[0] + "\n\n" + "".join(f"{p} {n}\n" for p, n in sorted(held.items())))
        print(f"file sizes: {len(kept)} file(s) listed over {BUDGET} lines, {len(held)} new one(s) over {NEW_BUDGET}")
        return 0

    errors, notes = [], []
    for path, n in sorted(over.items()):
        if path not in allowed:
            errors.append((path, f"{n} lines, over the {BUDGET}-line budget: split it into files that each do one thing"))
        elif n > allowed[path]:
            errors.append(
                (
                    path,
                    f"{n} lines, grown past the {allowed[path]} it is allowed (scripts/ci/file_sizes_allow.txt): "
                    f"take what grew into a file of its own",
                )
            )
    for path, count in sorted(allowed.items()):
        n = sizes.get(path, 0)
        if n < count:
            notes.append(f"{path}: {n} lines now, {count} allowed: `python3 scripts/ci/file_sizes.py --write` lowers it")

    # A new file: the owner's 300. Against REF where one is given, else (the
    # edit-time hook) against the last commit, so a file not yet committed
    # is new.
    new_ref = ref or ("HEAD" if given else None)
    if new_ref:
        listed = subprocess.run(["git", "-C", str(ROOT), "ls-tree", "-r", "--name-only", new_ref], capture_output=True, text=True)
        old = set(listed.stdout.splitlines()) if listed.returncode == 0 else set(sizes)
        for path, n in sorted(sizes.items()):
            if not (NEW_BUDGET < n <= BUDGET) or path in allowed or path in old:
                continue
            if path not in new_allowed:
                errors.append((path, f"{n} lines, a new file over the {NEW_BUDGET}-line budget for new files: split it"))
            elif n > new_allowed[path]:
                errors.append((path, f"{n} lines, grown past the {new_allowed[path]} scripts/ci/file_sizes_new_allow.txt holds"))

    if ref:
        shown = subprocess.run(
            ["git", "-C", str(ROOT), "show", f"{ref}:{ALLOW.relative_to(ROOT).as_posix()}"], capture_output=True, text=True
        )
        if shown.returncode == 0:
            before = read_allow(shown.stdout)
            for path, count in sorted(allowed.items()):
                if path not in before and path.endswith(COUNTED_SINCE_2026_11_12) and at(ref, path) is not None:
                    continue  # a file there at REF, of a kind first counted on 2026-11-12
                if path not in before:
                    errors.append((path, f"added to scripts/ci/file_sizes_allow.txt against {ref}: the list only shrinks"))
                elif count > before[path]:
                    errors.append(
                        (
                            path,
                            f"raised from {before[path]} to {count} in scripts/ci/file_sizes_allow.txt "
                            f"against {ref}: the list only shrinks",
                        )
                    )
        else:
            notes.append(f"no scripts/ci/file_sizes_allow.txt at {ref}: the list is not compared")
        shown = subprocess.run(
            ["git", "-C", str(ROOT), "show", f"{ref}:{NEW_ALLOW.relative_to(ROOT).as_posix()}"], capture_output=True, text=True
        )
        if shown.returncode == 0:
            before = read_allow(shown.stdout)
            for path, count in sorted(new_allowed.items()):
                if count > before.get(path, 0):
                    errors.append((path, f"added or raised in scripts/ci/file_sizes_new_allow.txt against {ref}: the list only shrinks"))

    for note in notes:
        print(note)
    for path, why in errors:
        print(f"::error file={path}::{why}")
    if errors:
        return 1
    print(f"file sizes: {len(sizes)} source files, none new or grown over {BUDGET} lines ({len(allowed)} listed)")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
