#!/usr/bin/env bash
# Put a branch live on the owner's local stack for them to try on the
# phone, before any lengthy test or CI (CLAUDE.md, Branches: "Live for
# the owner first"). The stack runs from its own worktree,
# ~/Developer/wingtip-live, so the main checkout stays on main; data/,
# .env and the local HTTPS certificates are linked from the main
# checkout, and the compose project is the same (wingtip), so the
# phone's address and the saved data don't change.
#
#   scripts/dev/go-live.sh                 claude/integration
#   scripts/dev/go-live.sh <branch>        another branch
set -euo pipefail
branch=${1:-claude/integration}
# The main checkout: from the script's own repo, or the current
# directory's when the script is run from a copy.
main=$(git -C "$(dirname "$0")/../.." rev-parse --path-format=absolute --git-common-dir 2>/dev/null \
  || git rev-parse --path-format=absolute --git-common-dir)
main=${main%/.git}
live=${WINGTIP_LIVE_DIR:-$HOME/Developer/wingtip-live}
export PATH="$PATH:$HOME/.docker/bin"
# The live tree is force-checked-out below: were it the main checkout (a
# WINGTIP_LIVE_DIR pointed there), the owner's uncommitted changes go.
if [ "$(cd "$live" 2>/dev/null && pwd -P || echo "$live")" = "$(cd "$main" && pwd -P)" ]; then
  echo "go-live: $live is the main checkout; the live stack needs a worktree of its own" >&2
  exit 1
fi

# Tidy first: merged worktrees and branches, stopped containers; and the
# merged worktrees left untouched for six hours, with their build outputs
# (the owner's efficiency rules, 2026-11-12).
"$(dirname "$0")/tidy-local.sh" || true
"$(dirname "$0")/tidy-branches.sh" || true
git -C "$main" fetch -q origin "$branch"
if [ ! -d "$live" ]; then
  git -C "$main" worktree add -q --detach "$live" "origin/$branch"
fi
git -C "$live" checkout -q --force --detach "origin/$branch"  # the live tree only mirrors the branch
# The owner's local files, shared rather than copied.
# .env and the certificates are read on the Mac, so links do; data/ is
# read inside the containers through the repo mount, where a link to a
# Mac path leads nowhere, so it is mounted over the worktree's own data/
# by a generated override instead.
if [ -L "$live/data" ]; then rm "$live/data"; git -C "$live" checkout -q -- data 2>/dev/null || mkdir -p "$live/data"; fi
for p in .env infra/local-https/certs; do
  if [ -e "$main/$p" ] && [ ! -L "$live/$p" ]; then
    rm -rf "${live:?}/$p"
    ln -s "$main/$p" "$live/$p"
  fi
done
cd "$live"
# Every service that mounts the repo at /workspace also gets the main
# checkout's data/ at /workspace/data (compose reads this file itself).
# The jobs (charts, charts-overlays, retrain) sit behind a profile and are
# left out of a plain `config`; they need the mount most, or a
# `docker compose --profile jobs run charts` writes into this worktree's
# own empty data/ (2026-11-08). --profile '*' lists every service.
docker compose -p wingtip --profile '*' config --format json | python3 -c '
import json, sys
main = sys.argv[1]
cfg = json.load(sys.stdin)
lines = ["# Generated by scripts/dev/go-live.sh: data/ from the main checkout.", "services:"]
for name, svc in sorted(cfg.get("services", {}).items()):
    if any(isinstance(v, dict) and v.get("target") == "/workspace" for v in svc.get("volumes", [])):
        lines += [f"  {name}:", "    volumes:", f"      - {main}/data:/workspace/data"]
print("\n".join(lines))
' "$main" > docker-compose.override.yml
echo "go-live: $(git log --oneline -1 | cut -c1-72)"
# The web build's packages for this tree, then every service rebuilt
# and restarted where its image or settings changed.
# The packages are installed with the web build stopped: an install
# beside a running build left half-written packages (2026-11-08).
docker compose -p wingtip stop web-build >/dev/null 2>&1 || true
docker compose -p wingtip run --rm --no-deps --entrypoint sh web-build -c "npm ci --no-audit --no-fund" 2>&1 | grep -iE "^npm (error|err)" || true
# The Mac's address can change (DHCP): the phone's address in .env and
# the gateway's certificate follow it; the phone keeps trusting the same
# authority, so it needs nothing new.
ip=$(ipconfig getifaddr en0 2>/dev/null || ipconfig getifaddr en1 2>/dev/null || true)
if [ -n "$ip" ] && ! grep -q "^PHONE_BASE_URL=https://$ip:8443" "$main/.env" 2>/dev/null; then
  echo "go-live: the Mac is now $ip; new certificate and PHONE_BASE_URL"
  sh "$main/infra/local-https/make-certs.sh" "$ip" >/dev/null
  sed -i '' -E "s#^PHONE_BASE_URL=.*#PHONE_BASE_URL=https://$ip:8443#" "$main/.env"
fi
docker compose -p wingtip up -d --build --remove-orphans
for _ in $(seq 1 40); do
  docker compose -p wingtip ps --format '{{.Health}}' | grep -q starting || break
  sleep 15
done
# A volume made under the bookworm image warns on every connection until
# its collation version is refreshed; once, then a no-op.
scripts/dev/pg-refresh-collation.sh
# The web build, once its first build is out, stops: only go-live.sh
# changes this tree, so a watching build only holds about 1.4 GB (the
# owner's efficiency rules, 2026-11-12). GO_LIVE_KEEP_WEB_BUILD=1 keeps it.
if [ "${GO_LIVE_KEEP_WEB_BUILD:-0}" != 1 ]; then
  for _ in $(seq 1 60); do
    docker compose -p wingtip logs --since 20m web-build 2>/dev/null | grep -q "built in" && break
    sleep 10
  done
  docker compose -p wingtip stop web-build >/dev/null 2>&1 || true
fi
docker compose -p wingtip ps --format '{{.Service}}: {{.Status}}'
host=$(grep -E '^PHONE_BASE_URL=' .env 2>/dev/null | cut -d= -f2-)
echo "go-live: live at ${host:-https://localhost:8443}/app"
